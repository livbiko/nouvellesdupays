// Falls back to French (the site's original/default language) if a
// country's primary language isn't in the table above -- shouldn't happen
// against the current 190-country dataset (every value in `languages` is
// covered), but a future country/language addition shouldn't ever render
// blank.
export function latestNewsHeading(languages: string[]): string {
  const primary = languages[0];
  return LATEST_NEWS_TRANSLATIONS[primary] ?? LATEST_NEWS_TRANSLATIONS.French;
}
