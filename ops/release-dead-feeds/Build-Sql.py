# Generates feeds.sql (apply) and rehearse.sql (same body, ROLLBACK) from one list so they cannot drift.
# Feed fixes: id, old feed_url, new feed_url, new feed_type, old-homepage domain (or None), new homepage.
FIX = [
    (216, 'https://www.journaldutchad.com/feed/', 'https://journaldutchad.com/feed/', 'rss', None, None),
    (254, 'https://www.madote.com/feed', 'http://www.madote.com/feeds/posts/default', 'rss', None, None),
    (284, 'https://www.verdade.co.mz/feed/', 'http://verdade.co.mz/feed/', 'rss', None, None),
    (296, 'https://www.observer.org.sz/feed', 'https://www.eswatiniobserver.com/feed/', 'rss', 'observer.org.sz', 'https://www.eswatiniobserver.com'),
    (521, 'https://www.monacomatin.mc/rss', 'https://www.nicematin.com/monaco/rss', 'rss', 'monacomatin.mc', 'https://www.nicematin.com/monaco'),
    (538, 'https://www.lastampa.it/rss.xml', 'https://www.lastampa.it/rss/copertina.xml', 'rss', None, None),
    (547, 'https://timesofmalta.com/rss/malta', 'https://timesofmalta.com/?feed=rss2', 'rss', None, None),
    (579, 'https://www.lrytas.lt/rss', 'https://www.lrytas.lt/rss.xml', 'rss', None, None),
    (1038, 'https://www.timesofisrael.com/feed/', 'https://www.timesofisrael.com/news-sitemap.xml', 'sitemap-news', None, None),
    (1519, 'https://www.channel5belize.com/feed/', 'https://www.greaterbelize.com/feed/', 'rss', 'channel5belize.com', 'https://www.greaterbelize.com'),
]
# Publishers with no reachable feed: TODAY (merged into CNA, publisher 996), China Daily (RSS removed), El Mundo SV
# (new site has no feed), Infos241 (redirect loop), Volksblatt (expired cert, 503), Daily News Botswana and ZNBC
# (broken TLS / unreachable), RTB (401), SSNA, TchadActuel, La Nation Djibouti (403/refused on every path),
# Agenda.ge, Newsday, CBC News (connection timeout from our servers).
GONE = [997, 962, 1524, 225, 524, 272, 279, 1003, 266, 218, 259, 1065, 1541, 1509]

def body():
    o = ["SET lock_timeout = '5s';", 'BEGIN;',
         "select 'before|feed|' || f.id || '|' || f.feed_type || '|' || f.feed_url || '|' || f.consecutive_failures || '|' || coalesce(f.etag,'-') || '|' || coalesce(f.last_modified,'-') || '|' || p.homepage_url"
         f" FROM feeds f JOIN publishers p ON p.id = f.publisher_id WHERE f.id IN ({', '.join(str(f[0]) for f in FIX)}) ORDER BY f.id;",
         "select 'before|pub|' || id || '|' || name || '|' || feed_status FROM publishers"
         f" WHERE id IN ({', '.join(map(str, GONE))}) ORDER BY id;",
         'DO $$', 'DECLARE n int := 0; h int := 0; g int; k int;', 'BEGIN']
    for (i, old, new, typ, dom, home) in FIX:
        o.append(f"  UPDATE feeds SET feed_url = '{new}', feed_type = '{typ}', etag = NULL, last_modified = NULL, consecutive_failures = 0, last_error = NULL"
                 f" WHERE id = {i} AND publisher_id = {i} AND feed_url = '{old}' AND enabled; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;")
        if dom:
            o.append(f"  UPDATE publishers SET homepage_url = '{home}' WHERE id = {i} AND homepage_url LIKE '%{dom}%'; GET DIAGNOSTICS k = ROW_COUNT; h := h + k;")
    o.append(f"  UPDATE publishers SET feed_status = 'unavailable' WHERE id IN ({', '.join(map(str, GONE))}) AND feed_status = 'active'; GET DIAGNOSTICS g = ROW_COUNT;")
    nh = sum(1 for f in FIX if f[4])
    o.append(f"  IF n <> {len(FIX)} OR h <> {nh} OR g <> {len(GONE)} THEN RAISE EXCEPTION 'expected {len(FIX)} feeds / {nh} homepages / {len(GONE)} publishers at their starting values, got % / % / %', n, h, g; END IF;")
    o += ['END $$;',
          "select 'after|feed|' || f.id || '|' || f.feed_type || '|' || f.feed_url || '|' || p.homepage_url FROM feeds f JOIN publishers p ON p.id = f.publisher_id"
          f" WHERE f.id IN ({', '.join(str(f[0]) for f in FIX)}) ORDER BY f.id;",
          "select 'after|unavailable|' || count(*) FROM publishers WHERE id IN (" + ', '.join(map(str, GONE)) + ") AND feed_status = 'unavailable';"]
    return o

hdr = [r'\set ON_ERROR_STOP on']
open('feeds.sql', 'w', newline='\n').write('\n'.join(
    ['-- Dead-feed fix (data only, MEDIUM). Generated by Build-Sql.py - edit the list there, not this file.',
     '-- One guarded transaction: aborts unless every row is at its starting value. Reverse: feeds-reverse.sql.'] + hdr + body() + ['COMMIT;']) + '\n')
open('rehearse.sql', 'w', newline='\n').write('\n'.join(
    ['-- Rehearsal of feeds.sql: the same statements, then ROLLBACK. Generated by Build-Sql.py.'] + hdr + body() + ['ROLLBACK;',
     "select 'rolledback|' || count(*) FILTER (WHERE feed_status = 'active') || ' of " + str(len(GONE)) + " still active' FROM publishers WHERE id IN (" + ', '.join(map(str, GONE)) + ");"]) + '\n')
print('ok', len(FIX), len(GONE))

# Reverse: back to the starting URLs/types/homepages (values from rehearse.txt) and feed_status 'active'.
# Failure counters restart from 0; the backoff counts from last_success_at, so the old feeds are held back again
# after one failing day.
OLD_HOME = {296: 'https://www.observer.org.sz', 521: 'https://www.monacomatin.mc', 1519: 'https://www.channel5belize.com'}
r = [r'\set ON_ERROR_STOP on', "SET lock_timeout = '5s';", 'BEGIN;', 'DO $$', 'DECLARE n int := 0; h int := 0; g int; k int;', 'BEGIN']
for (i, old, new, typ, dom, home) in FIX:
    r.append(f"  UPDATE feeds SET feed_url = '{old}', feed_type = 'rss', etag = NULL, last_modified = NULL WHERE id = {i} AND feed_url = '{new}'; GET DIAGNOSTICS k = ROW_COUNT; n := n + k;")
    if dom:
        r.append(f"  UPDATE publishers SET homepage_url = '{OLD_HOME[i]}' WHERE id = {i} AND homepage_url = '{home}'; GET DIAGNOSTICS k = ROW_COUNT; h := h + k;")
r.append(f"  UPDATE publishers SET feed_status = 'active' WHERE id IN ({', '.join(map(str, GONE))}) AND feed_status = 'unavailable'; GET DIAGNOSTICS g = ROW_COUNT;")
r.append(f"  IF n <> {len(FIX)} OR h <> {len(OLD_HOME)} OR g <> {len(GONE)} THEN RAISE EXCEPTION 'reverse: expected {len(FIX)} / {len(OLD_HOME)} / {len(GONE)}, got % / % / %', n, h, g; END IF;")
r += ['END $$;', 'COMMIT;', "select 'reversed|' || count(*) FILTER (WHERE feed_status = 'active') || ' of " + str(len(GONE)) + " active' FROM publishers WHERE id IN (" + ', '.join(map(str, GONE)) + ');']
open('feeds-reverse.sql', 'w', newline='\n').write('-- Reverse of feeds.sql. Generated by Build-Sql.py.\n' + '\n'.join(r) + '\n')

# Verify (read-only): the fixed feeds after the first poll, and the publishers now unavailable.
ids = ', '.join(str(f[0]) for f in FIX)
open('verify.sql', 'w', newline='\n').write('\n'.join([
    "select 'feed|' || f.id || '|' || p.name || '|' || f.consecutive_failures || '|' || coalesce(to_char(f.last_success_at, 'HH24:MI'), 'never') || '|' || coalesce(f.last_error, '-') ||"
    " '|' || (SELECT count(*) FROM articles a WHERE a.publisher_id = f.publisher_id AND a.fetched_at > now() - interval '1 hour') || ' new'"
    f" FROM feeds f JOIN publishers p ON p.id = f.publisher_id WHERE f.id IN ({ids}) ORDER BY f.id;",
    "select 'ok|' || count(*) FILTER (WHERE f.last_success_at > now() - interval '30 minutes') || ' of " + str(len(FIX)) + " fixed feeds succeeded in the last 30 min'"
    f" FROM feeds f WHERE f.id IN ({ids});",
    "select 'unavailable|' || count(*) FROM publishers WHERE feed_status = 'unavailable' AND id IN (" + ', '.join(map(str, GONE)) + ');']) + '\n')
print('reverse + verify ok')
