# Build #108 - label_time_zone Europe/Paris on Jeune Afrique (data only). Feed dates are exactly 2 h later than the
# article pages' own published_time on every sampled item: Paris time (CEST) labelled +00:00. Checked on the live feed with
# buildArticleRow: 0 items ahead, newest 48 min old. JPost and Daily Maverick feed = page (left alone); RTP pages carry no date.
import json

FEEDS = [  # publisher_id, feed_url, zone
    (5207, 'https://www.jeuneafrique.com/feed', 'Europe/Paris'),
]
IDS = ', '.join(str(p) for p, _, _ in FEEDS)
HDR = '\\set ON_ERROR_STOP on\n'


def q(s):
    return "'" + s.replace("'", "''") + "'"


steps = ''
for pid, url, off in FEEDS:
    steps += f"""  UPDATE feeds SET parser_config = '{{"label_time_zone": "{off}"}}'::jsonb
   WHERE publisher_id = {pid} AND feed_url = {q(url)} AND feed_type = 'rss' AND enabled AND parser_config = '{{}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % feed rows with an empty parser_config, expected 1 - nothing changed', k; END IF;
"""
BODY = f"""SET lock_timeout = '5s';
BEGIN;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'config|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;"""

with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Build #108 label_time_zone on Jeune Afrique (data only, MEDIUM). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n'
             f"SELECT 'rolledback|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;\n")
rev = ''.join(f"""  UPDATE feeds SET parser_config = '{{}}'::jsonb WHERE publisher_id = {pid} AND parser_config = '{{"label_time_zone": "{off}"}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
""" for pid, _, off in FEEDS)
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: parser_config back to '{{}}'. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
{rev}END $do$;
COMMIT;
SELECT 'reversed|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;
""")
with open('verify.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Read-only, ~30 min after apply. Rows fetched since then should no longer sit at their fetch time, nor after it.
SELECT 'new|' || a.publisher_id || '|' || count(*) || ' new|' || count(*) FILTER (WHERE abs(extract(epoch FROM a.published_at - a.fetched_at)) < 5) || ' at fetch time|'
       || count(*) FILTER (WHERE a.published_at > a.fetched_at) || ' after fetch|newest ' || coalesce(to_char(max(a.published_at), 'HH24:MI'), '-') || ' (fetched ' || coalesce(to_char(max(a.fetched_at), 'HH24:MI'), '-') || ')'
  FROM articles a WHERE a.publisher_id IN ({IDS}) AND a.fetched_at > now() - interval '30 minutes' GROUP BY a.publisher_id ORDER BY 1;
""")
print('ok', len(FEEDS))
