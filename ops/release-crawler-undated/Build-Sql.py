# Build #95 - undated rows of five HTML-crawler publishers (data only, MEDIUM). Generates apply.sql, rehearse.sql, reverse.sql, verify.sql.
# 2026-10-19: the weekly silent report listed them as "never (no dated article)"; every one of their rows has published_at NULL,
# so the site hides them all (same cause as Build #86 for RSS):
#   GRTS (8917)            article pages show the date after a clock icon ('data-feather="clock"></i> <span>October 18, 2026 06:00');
#                          checked with extractArticleMeta -> 2026-10-18T06:00Z. Rule + fetch_time fallback.
#   Inforpress (8918)      Next.js page, dates only inside embedded JSON (not reliably targetable) -> undated=fetch_time.
#   Conakry Live (8925)    no usable date found -> undated=fetch_time.
#   Seychelles Nation (8949), Courrier Confidentiel (8956): their date rules already work since Build #87 (checked on live
#                          pages); only their older rows, stored before #87, are undated -> backfill only, config untouched.
#  A. One guarded transaction: parser_config for 8917/8918/8925 (each must still be '{}').
#  B. Backfill, autocommit batches of 500 + 4 s pause + lock-waiter stop: undated rows of the five fetched in the last
#     14 days get published_at = fetched_at.
# Reverse: A restores '{}'; B sets published_at back to NULL where published_at = fetched_at exactly.
import json

CONFIG = {  # publisher_id: new parser_config (old must be {})
    8917: {'date_after_label': 'data-feather="clock"', 'utc_offset': '+00:00', 'undated': 'fetch_time'},
    8918: {'undated': 'fetch_time'},
    8925: {'undated': 'fetch_time'},
}
ALL = [8917, 8918, 8925, 8949, 8956]
IDS = ', '.join(str(p) for p in ALL)
CIDS = ', '.join(str(p) for p in CONFIG)
WINDOW = "now() - interval '14 days'"


def js(d):
    return "'" + json.dumps(d).replace("'", "''") + "'::jsonb"


steps = ''
for pid, cfg in CONFIG.items():
    steps += f"""  UPDATE feeds SET parser_config = {js(cfg)}
   WHERE publisher_id = {pid} AND feed_type = 'html' AND enabled AND parser_config = '{{}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % html feed rows with an empty parser_config, expected 1 - nothing changed', k; END IF;
"""

PART_A = f"""SET lock_timeout = '5s';
BEGIN;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'config|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;"""

COUNT = f"""SELECT 'undated|' || publisher_id || '|' || count(*) || '|in window=' || count(*) FILTER (WHERE fetched_at > {WINDOW})
  FROM articles WHERE publisher_id IN ({IDS}) AND published_at IS NULL GROUP BY publisher_id ORDER BY publisher_id;"""

PART_B = f"""CREATE TEMP TABLE batch_ids AS
  SELECT id, ((row_number() OVER (ORDER BY id)) - 1) / 500 AS b FROM articles
   WHERE publisher_id IN ({IDS}) AND published_at IS NULL AND fetched_at > {WINDOW};
CREATE INDEX ON batch_ids (b); ANALYZE batch_ids;
SELECT 'batches|' || count(*) || ' rows|' || coalesce(max(b) + 1, 0) || ' batches' FROM batch_ids;
SET statement_timeout = '15s';
SELECT 'DO $w$ BEGIN IF EXISTS (SELECT 1 FROM pg_stat_activity WHERE datname = current_database() AND pid <> pg_backend_pid() AND wait_event_type = ''Lock'' AND now() - query_start > interval ''30 seconds'') THEN RAISE EXCEPTION ''stopping: a session has waited on a lock for over 30s''; END IF; END $w$',
       format('UPDATE articles a SET published_at = a.fetched_at FROM batch_ids i WHERE i.b = %s AND a.id = i.id AND a.published_at IS NULL', b),
       'SELECT pg_sleep(4)'
  FROM generate_series(0, coalesce((SELECT max(b) FROM batch_ids), -1)) b ORDER BY b
\\gexec
RESET statement_timeout;"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Build #95: crawler parser_config (A), then a batched 14-day backfill (B). Generated by Build-Sql.py.\n"
             f"-- B runs in autocommit batches: never wrap this file in BEGIN. Reverse: reverse.sql.\n{HDR}{COUNT}\n{PART_A}\nCOMMIT;\n{PART_B}\n{COUNT}\n"
             f"SELECT 'left|' || count(*) || ' undated in window' FROM articles WHERE publisher_id IN ({IDS}) AND published_at IS NULL AND fetched_at > {WINDOW};\n")
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal: part A in a rolled-back transaction, and part B's row count only (no update). Generated by Build-Sql.py.\n"
             f"{HDR}{COUNT}\n{PART_A}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;\n"
             f"SELECT 'would-backfill|' || count(*) || ' rows|' || ceil(count(*) / 500.0) || ' batches' FROM articles WHERE publisher_id IN ({IDS}) AND published_at IS NULL AND fetched_at > {WINDOW};\n")
rev = ''
for pid, cfg in CONFIG.items():
    rev += f"""  UPDATE feeds SET parser_config = '{{}}'::jsonb WHERE publisher_id = {pid} AND parser_config = {js(cfg)};
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: parser_config back to '{{}}' (one transaction), then backfilled dates back to NULL in batches. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
{rev}END $do$;
COMMIT;
CREATE TEMP TABLE batch_ids AS
  SELECT id, ((row_number() OVER (ORDER BY id)) - 1) / 500 AS b FROM articles WHERE publisher_id IN ({IDS}) AND published_at = fetched_at;
SET statement_timeout = '15s';
SELECT format('UPDATE articles a SET published_at = NULL FROM batch_ids i WHERE i.b = %s AND a.id = i.id AND a.published_at = a.fetched_at', b), 'SELECT pg_sleep(4)'
  FROM generate_series(0, coalesce((SELECT max(b) FROM batch_ids), -1)) b ORDER BY b
\\gexec
RESET statement_timeout;
{COUNT}
""")
with open('verify.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Read-only, after the first poll. Generated by Build-Sql.py.
{COUNT}
SELECT 'new|' || publisher_id || '|' || count(*) || ' since apply|' || count(*) FILTER (WHERE published_at IS NULL) || ' undated|newest ' || coalesce(to_char(max(published_at), 'MM-DD HH24:MI'), '-')
  FROM articles WHERE publisher_id IN ({IDS}) AND fetched_at > now() - interval '40 minutes' GROUP BY publisher_id ORDER BY 1;
SELECT 'silent|' || p.id || '|' || p.name || '|' || coalesce(to_char(max(a.published_at), 'MM-DD'), 'never')
  FROM publishers p LEFT JOIN articles a ON a.publisher_id = p.id AND a.published_at IS NOT NULL AND a.published_at < now() + interval '1 day'
 WHERE p.id IN ({IDS}) GROUP BY p.id, p.name ORDER BY p.id;
""")
print('ok')
