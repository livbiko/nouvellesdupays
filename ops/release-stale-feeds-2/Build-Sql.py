# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql: second batch from the 2026-10-17 stale sweep.
#  - 3 feeds fixed. Radio Okapi's /rss.xml is a frozen endpoint (newest 2026-09-29); /feed/ is current. SANA and Le Mauricien
#    sit behind a WordPress page cache stuck on the plain /feed/ URL (frozen 2026-09-29 and 2026-08-07); the same feed with a
#    fixed query string is current, so it is stored as /feed/?src=ndp (honest, constant marker; the admin "Silencieux"
#    filter shows it if that ever freezes too). All three tested with the worker's own parser + buildArticleRow.
#  - 4 publishers -> feed_status 'unavailable' (like Build #68 / #77): RMI Government (rmigovernment.org hijacked: feed
#    now Thai football-betting spam; 0 articles stored), Liberte-Algerie (paper closed April 2022; site frozen), MadaGate
#    (nothing since 2022-05), Madote (blog, nothing since 2020-11).
#  - Liberte-Algerie's 20 articles are 2022 pieces stored undated on 2026-07-26 (its "12:00 | 14-04-2022" dates don't
#    parse): deleted. No foreign key references articles. reverse.sql cannot bring them back (recovery point backup only).
# Every statement is guarded; the transaction aborts unless each touches exactly the expected rows.

FEEDS = [  # publisher_id, name, old_url, new_url, tested
    (230, 'Radio Okapi', 'https://www.radiookapi.net/rss.xml', 'https://www.radiookapi.net/feed/', '50/50, 2026-10-17'),
    (1052, 'SANA', 'https://sana.sy/en/?feed=rss2', 'https://sana.sy/en/feed/?src=ndp', '10/10, 2026-10-17'),
    (301, 'Le Mauricien', 'https://www.lemauricien.com/feed', 'https://www.lemauricien.com/feed/?src=ndp', '10/10, 2026-10-17'),
]
UNAVAILABLE = [(2078, 'RMI Government'), (169, 'Liberté-Algérie'), (298, 'MadaGate'), (254, 'Madote')]
N_LIBERTE = 20
IDS = ', '.join(str(i) for i in [f[0] for f in FEEDS] + [u[0] for u in UNAVAILABLE])


def dq(s):
    assert '$$' not in s
    return f'$${s}$$'


steps = ''
for pid, name, old, new, _ in FEEDS:
    steps += f"""  UPDATE feeds SET feed_url = '{new}', etag = NULL, last_modified = NULL
   WHERE publisher_id = {pid} AND feed_url = '{old}' AND feed_type = 'rss' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % feed rows at the old URL, expected 1 - nothing changed', k; END IF;
"""
steps += f"""  DELETE FROM articles WHERE publisher_id = 169 AND published_at IS NULL AND original_url LIKE 'https://www.liberte-algerie.com/%'
   AND fetched_at < DATE '2026-07-27';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> {N_LIBERTE} THEN RAISE EXCEPTION 'Liberte-Algerie: % undated articles, expected {N_LIBERTE} - nothing changed', k; END IF;
  IF EXISTS (SELECT 1 FROM articles WHERE publisher_id = 169) THEN RAISE EXCEPTION 'Liberte-Algerie has other articles - nothing changed'; END IF;
"""
for pid, name in UNAVAILABLE:
    steps += f"""  UPDATE publishers SET feed_status = 'unavailable' WHERE id = {pid} AND name = {dq(name)} AND feed_status = 'active';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: not the active {name} - nothing changed'; END IF;
"""

BODY = f"""SET lock_timeout = '5s';
BEGIN;
SELECT 'before|' || p.id || '|' || p.feed_status || '|' || coalesce(f.feed_url, '-') FROM publishers p LEFT JOIN feeds f ON f.publisher_id = p.id AND f.enabled WHERE p.id IN ({IDS}) ORDER BY p.id;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'after|' || p.id || '|' || p.feed_status || '|' || coalesce(f.feed_url, '-') || '|' || (SELECT count(*) FROM articles a WHERE a.publisher_id = p.id AND p.id = 169) FROM publishers p LEFT JOIN feeds f ON f.publisher_id = p.id AND f.enabled WHERE p.id IN ({IDS}) ORDER BY p.id;"""

rev = ''
for pid, name, old, new, _ in FEEDS:
    rev += f"""  UPDATE feeds SET feed_url = '{old}', etag = NULL, last_modified = NULL WHERE publisher_id = {pid} AND feed_url = '{new}' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""
for pid, name in UNAVAILABLE:
    rev += f"""  UPDATE publishers SET feed_status = 'active' WHERE id = {pid} AND feed_status = 'unavailable';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Stale sweep batch 2: 3 feeds fixed, 4 publishers unavailable, 20 undated 2022 Liberte-Algerie articles deleted (data only). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || p.id || '|' || p.feed_status || '|' || (SELECT count(*) FROM articles a WHERE a.publisher_id = 169 AND p.id = 169) FROM publishers p WHERE p.id IN ({IDS}) ORDER BY p.id;\n")
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Reverse of apply.sql (the 20 deleted Liberte-Algerie articles come back only from the recovery point's DB backup). Generated by Build-Sql.py.\n"
             f"{HDR}SET lock_timeout = '5s';\nBEGIN;\nDO $do$ DECLARE k int; BEGIN\n{rev}END $do$;\nCOMMIT;\n")
print('ok')
