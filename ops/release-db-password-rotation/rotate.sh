#!/bin/bash
# Build #206 -- rotate the on-prem Postgres app-role password (nouvellesdupays on dr-postgres 192.168.1.52).
# Copy this directory to dr-rke2 and run there:
#   bash rotate.sh apply      # new random password: role + nouvellesdupays-secrets, API restarted
#   bash rotate.sh finish     # only if apply stopped after the role was changed: write the secret + restart
#   bash rotate.sh rollback   # back to the password kept in nouvellesdupays-secrets-prev-b206
#   bash rotate.sh cleanup    # after verification: delete the kept copy (the old password counts as leaked)
# No password is ever on a command line, in a pod spec or in this script's output: it is generated by python's
# secrets module, travels through stdin and Kubernetes secrets, and switch.js sends Postgres a SCRAM verifier.
set -euo pipefail
K="sudo /var/lib/rancher/rke2/bin/kubectl --kubeconfig /etc/rancher/rke2/rke2.yaml -n nouvellesdupays"
here=$(cd "$(dirname "$0")" && pwd)
MAIN=nouvellesdupays-secrets
PREV=nouvellesdupays-secrets-prev-b206
TMP=ndp-rotate-b206
mode=${1:-}

suspended=""
resume() { for c in $suspended; do $K patch cronjob "$c" -p '{"spec":{"suspend":false}}' >/dev/null && echo "resumed cronjob $c"; done; }
pause_jobs() {
  trap resume EXIT
  for c in $($K get cronjob -o jsonpath='{range .items[?(@.spec.suspend==false)]}{.metadata.name}{"\n"}{end}' | grep '^nouvellesdupays-'); do
    $K patch cronjob "$c" -p '{"spec":{"suspend":true}}' >/dev/null && suspended="$suspended $c" && echo "suspended cronjob $c"
  done
  for i in $(seq 1 72); do        # up to 6 min (the worker's own deadline is 280 s)
    active=$($K get jobs -o jsonpath='{range .items[?(@.status.active)]}{.metadata.name}{" "}{end}' | tr ' ' '\n' | grep '^nouvellesdupays-' || true)
    [ -z "$active" ] && return 0
    sleep 5
  done
  echo "jobs still running after 6 min, nothing changed: $active"; exit 4
}

# Runs switch.js in a worker-image pod. $1 = env JSON entries for FROM_URL and TO_PASSWORD/TO_URL (secret refs only).
run_switch() {
  local pod="pw-switch-$(date +%H%M%S)" phase="" code=""
  local script; script=$(base64 -w0 "$here/switch.js")
  $K run "$pod" --restart=Never --image=192.168.1.51:30500/nouvellesdupays-worker:local --overrides="$(cat <<JSON
{"spec":{"restartPolicy":"Never","containers":[{"name":"$pod","image":"192.168.1.51:30500/nouvellesdupays-worker:local",
  "command":["sh","-c","echo \"\$SCRIPT_B64\" | base64 -d > /tmp/switch.js && node /tmp/switch.js"],
  "env":[{"name":"SCRIPT_B64","value":"$script"},$1]}]}}
JSON
)" >/dev/null
  for i in $(seq 1 90); do
    phase=$($K get pod "$pod" -o jsonpath='{.status.phase}' 2>/dev/null || true)
    [ "$phase" = Succeeded ] || [ "$phase" = Failed ] && break
    sleep 2
  done
  $K logs "$pod" 2>&1 | sed 's/^/    switch: /' || true
  $K delete pod "$pod" --wait=false >/dev/null 2>&1 || true
  [ "$phase" = Succeeded ]
}

# Secret JSON on stdin -> the same secret with DATABASE_URL's password replaced (source named in argv, value read
# from the secrets in the List). The last-applied annotation is dropped: it would keep a copy of the old value.
set_url_py='
import json, sys, base64
mode = sys.argv[1]
items = {i["metadata"]["name"]: i for i in json.load(sys.stdin)["items"]}
main = items["nouvellesdupays-secrets"]
d = lambda s, k: base64.b64decode(s["data"][k]).decode()
if mode == "new":
    url = d(main, "DATABASE_URL"); pw = d(items["ndp-rotate-b206"], "TO_PASSWORD")
    scheme, rest = url.split("://", 1); cred, host = rest.split("@", 1)
    new = scheme + "://" + cred.split(":", 1)[0] + ":" + pw + "@" + host
else:
    new = d(items["nouvellesdupays-secrets-prev-b206"], "DATABASE_URL")
main["data"]["DATABASE_URL"] = base64.b64encode(new.encode()).decode()
md = main["metadata"]
for k in ("resourceVersion", "uid", "creationTimestamp", "managedFields"): md.pop(k, None)
(md.get("annotations") or {}).pop("kubectl.kubernetes.io/last-applied-configuration", None)
print(json.dumps(main))
'

restart_api() {
  $K rollout restart deployment/nouvellesdupays-api >/dev/null
  $K rollout status deployment/nouvellesdupays-api --timeout=240s
}

finish() {
  $K get secret "$MAIN" "$TMP" -o json | python3 -c "$set_url_py" new | $K replace -f - >/dev/null
  echo "$MAIN: DATABASE_URL now carries the new password"
  $K delete secret "$TMP" >/dev/null && echo "deleted $TMP"
  restart_api
}

case $mode in
apply)
  if $K get secret "$PREV" >/dev/null 2>&1; then echo "$PREV already exists -- apply ran before; use finish/rollback/cleanup"; exit 2; fi
  pause_jobs
  # Keep the current secret as $PREV (values through stdin only, without the last-applied annotation).
  $K get secret "$MAIN" -o json | python3 -c '
import json, sys
s = json.load(sys.stdin)
print(json.dumps({"apiVersion": "v1", "kind": "Secret", "type": s.get("type", "Opaque"),
  "metadata": {"name": "nouvellesdupays-secrets-prev-b206", "labels": {"ndp-build": "206"}}, "data": s["data"]}))
' | $K create -f - >/dev/null
  echo "kept the current secret as $PREV"
  python3 -c '
import json, secrets, string, base64
pw = "".join(secrets.choice(string.ascii_letters + string.digits) for _ in range(32))
print(json.dumps({"apiVersion": "v1", "kind": "Secret", "type": "Opaque",
  "metadata": {"name": "ndp-rotate-b206", "labels": {"ndp-build": "206"}},
  "data": {"TO_PASSWORD": base64.b64encode(pw.encode()).decode()}}))
' | $K create -f - >/dev/null
  echo "generated a new 32-character password into $TMP"
  if ! run_switch '{"name":"FROM_URL","valueFrom":{"secretKeyRef":{"name":"'$MAIN'","key":"DATABASE_URL"}}},{"name":"TO_PASSWORD","valueFrom":{"secretKeyRef":{"name":"'$TMP'","key":"TO_PASSWORD"}}}'; then
    # Both secrets are kept: if the pod died after the ALTER, $TMP holds the only copy of the password now in use.
    echo "switch FAILED -- $MAIN unchanged; $TMP and $PREV kept. If the log shows 'previous password restored'"
    echo "(or the ALTER never ran), run cleanup; if it shows 'password changed' but no restore, run finish."; exit 1
  fi
  echo "role password changed and the new login verified"
  finish || { echo "role has the NEW password but finishing failed -- run: bash rotate.sh finish"; exit 1; }
  echo "apply done"
  ;;
finish)
  $K get secret "$TMP" >/dev/null || { echo "$TMP not found -- nothing to finish"; exit 2; }
  pause_jobs
  finish
  ;;
rollback)
  $K get secret "$PREV" >/dev/null || { echo "$PREV not found -- nothing to roll back to"; exit 2; }
  pause_jobs
  run_switch '{"name":"FROM_URL","valueFrom":{"secretKeyRef":{"name":"'$MAIN'","key":"DATABASE_URL"}}},{"name":"TO_URL","valueFrom":{"secretKeyRef":{"name":"'$PREV'","key":"DATABASE_URL"}}}' \
    || { echo "rollback switch FAILED -- secrets unchanged"; exit 1; }
  $K get secret "$MAIN" "$PREV" -o json | python3 -c "$set_url_py" prev | $K replace -f - >/dev/null
  echo "$MAIN: DATABASE_URL restored from $PREV"
  restart_api
  echo "rollback done ($PREV kept; run cleanup once settled)"
  ;;
cleanup)
  $K delete secret "$PREV" "$TMP" --ignore-not-found
  ;;
*)
  echo "usage: bash rotate.sh apply|finish|rollback|cleanup"; exit 2
  ;;
esac
