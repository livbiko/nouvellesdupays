// CR-2026-11-17-02 review material (read-only): mapping.md (old -> new categories) and classification.csv (a proposed
// subcategory per directory channel and approved creator, for the owner to correct before anything is applied).
// Usage: node build-review.js <categories.txt slug|parent|name_fr|links|approved|primary> <chans.tsv>
const fs = require('fs');
const path = require('path');
const tree = require('./tree');

const [catsFile, chansFile] = process.argv.slice(2);
const old = fs.readFileSync(catsFile, 'utf8').trim().split(/\r?\n/).map((l) => {
  const [slug, parent, name, links, approved] = l.split('|');
  return { slug, parent: parent === '-' ? null : parent, name, links: +links, approved: +approved };
});

// --- the tree -------------------------------------------------------------------------------------------------------
const subs = new Map(); // slug -> { parent, name_fr, name_en, from }
let nSubs = 0;
for (const [slug, , , , children] of tree) {
  for (const [s, fr, en, from] of children) { subs.set(s, { parent: slug, fr, en, from }); nSubs += 1; }
}
if (tree.length !== 8 || nSubs !== 70) throw new Error(`tree has ${tree.length} categories / ${nSubs} subcategories, expected 8 / 70`);
const allSlugs = new Set([...tree.map((t) => t[0]), ...subs.keys()]);
if (allSlugs.size !== 78) throw new Error('duplicate slug in tree');
const keptFrom = new Map();
for (const [slug, fr, , from] of tree) if (from) keptFrom.set(from, { slug, fr, parent: null });
for (const [s, v] of subs) if (v.from) keptFrom.set(v.from, { slug: s, fr: v.fr, parent: v.parent });

// --- mapping.md -----------------------------------------------------------------------------------------------------
const nameOf = (slug) => (tree.find((t) => t[0] === slug) || [])[1] || subs.get(slug)?.fr || slug;
const lines = [];
lines.push('# CR-2026-11-17-02 — category map (for owner review)', '');
lines.push('Generated by `build-review.js` from `tree.js` and the live categories (read-only, 11-18). Nothing is applied until the', 'CR window. **No category and no link is deleted.**', '');
lines.push('## 1. Existing categories (49) → new tree', '');
lines.push('| Existing slug | Today (French) | Links (approved) | Becomes | Action |', '|---|---|---|---|---|');
for (const o of old) {
  const k = keptFrom.get(o.slug);
  let becomes; let action;
  if (k) {
    const where = k.parent ? `${nameOf(k.parent)} › ${k.fr}` : `${k.fr} (catégorie)`;
    becomes = where;
    const moved = (k.parent || null) !== (o.parent || null);
    const renamed = k.fr !== o.name;
    action = [moved ? 'moved' : null, renamed ? 'renamed' : null].filter(Boolean).join(' + ') || 'kept';
  } else {
    becomes = '—';
    action = o.links ? `switched off (its ${o.links} links stay; they count for the parent until reclassified)` : 'switched off (no links)';
  }
  lines.push(`| \`${o.slug}\` | ${o.name} | ${o.links} (${o.approved}) | ${becomes} | ${action} |`);
}
lines.push('', '## 2. The new tree (8 categories, 70 subcategories)', '');
for (const [slug, fr, en, from, children] of tree) {
  lines.push(`### ${fr} — \`${slug}\`${from ? '' : ' (new)'}`, '');
  for (const [s, cfr, cen, cfrom] of children) {
    lines.push(`- ${cfr} — \`${s}\` · ${cen}${cfrom ? (cfrom === s ? '' : ` · from \`${cfrom}\``) : ' · **new**'}`);
  }
  lines.push('');
}
lines.push('## 3. Rules', '');
lines.push('- Slugs of kept categories do not change, so existing links and URLs keep working; only names and parents change.');
lines.push('- A switched-off category is hidden on the site; a link to it counts for its parent (or, for a switched-off main');
lines.push('  category, for nothing) until a reviewer moves it. The admin page can switch it back on.');
lines.push('- Names on the site are French (owner rule 11-16); the English names are kept in `name_en` for the admin and future pages.');
fs.writeFileSync(path.join(__dirname, 'mapping.md'), lines.join('\n') + '\n');

// --- classification.csv ---------------------------------------------------------------------------------------------
const rows = fs.readFileSync(chansFile, 'utf8').split(/\r?\n/).filter((l) => /^(VC|CR)\t/.test(l)).map((l) => {
  const [kind, key, name, countries, rails, topics, descr, current] = l.split('\t');
  return { kind, key, name, countries, rails: rails.split(','), topics: topics.split(','), descr: descr || '', current: current || '' };
});

// International broadcasters by their own name only ("CNN Brasil", "Euronews Albania" are national editions).
const INTERNATIONAL = /^(france ?24( english| arabic| español)?|al ?jazeera( english| arabic)?|bbc (news|world( service)?)|cnn( international)?|dw( news)?|deutsche welle|rt( international| arabic| en español)?|euronews|cgtn|trt world|africanews|sky news|nhk world|arirang|i24 ?news|tv5 ?monde|rfi|voa|voice of america|al arabiya|wion|bloomberg|reuters)$/i;
const TV_NAME = /(tv|t[ée]l[ée]|television|channel|\b(ktn|ortm|rti|rts\d?|ortb|crtv|nta|ebc|znbc|zbc|nci|kbc|ortn|ortc|rtb|rtnc)\b|gabon ?1|news ?24)/i;
const KW = [
  [/\b(radio|fm)\b/i, 'radio-stations'],
  [/(sport|foot|soccer|ligue|olymp)/i, 'sports-news'],
  [/(gospel|église|eglise|church|islam|chr[ée]tien|christian|catholi|coran|quran|minist(ry|ère)|prophet)/i, 'religion-spirituality'],
  [/(parlement|parliament|assembl[ée]e nationale|s[ée]nat|senate|pr[ée]sidence|presidency|gouvernement|government)/i, 'government-institutions'],
  [/([ée]lection|electoral|vote)/i, 'elections'],
  [/(investigat|enqu[êe]te)/i, 'investigative'],
  [/(d[ée]bat|debate|interview|entretien|talk ?show)/i, 'interviews-debates'],
  [/(diaspora)/i, 'diaspora'],
  [/(business|[ée]conomi|finance|bourse|market)/i, 'business-news'],
  [/(musique|music|chanson|concert)/i, 'music'],
  [/(culture|patrimoine|heritage|tradition)/i, 'african-culture'],
  [/(g[ée]opoliti|politi)/i, 'political-analysis'],
];
// Existing creator categories -> new subcategory (kept slugs map to themselves).
const CREATOR_MAP = { 'other-sports': 'sports-news', entertainment: 'entertainment-shows', lifestyle: 'lifestyle-living',
  'culture-society': 'social-issues', 'digital-gaming': 'technology', 'education-knowledge': 'education', 'news-media': 'news-current-affairs',
  beauty: 'fashion', journalism: 'news-current-affairs', 'digital-marketing': 'digital-innovation' };

function propose(r) {
  const text = `${r.name} ${r.descr}`;
  const hits = KW.filter(([re]) => re.test(text)).map(([, s]) => s);
  const multi = r.countries.split(',').filter((c) => c !== '--').length > 1;
  let primary; let others = []; let confidence = 'low'; let reason;
  if (r.kind === 'CR') {
    const cur = r.current.split(',').filter(Boolean);
    const prim = (cur.find((c) => c.endsWith('*')) || cur[0] || '').replace('*', '');
    const mapped = (s) => (subs.has(s) ? s : CREATOR_MAP[s] || null);
    primary = mapped(prim);
    others = cur.map((c) => mapped(c.replace('*', ''))).filter((s) => s && s !== primary);
    confidence = primary ? 'medium' : 'low';
    reason = `current categories ${r.current || '(none)'}; kind ${r.rails.join(',')}`;
    // A media brand is first a news outlet (discovery's topic mapping put many under social issues); its old
    // categories become secondary. An individual talking politics is political analysis rather than political news.
    if (r.rails.includes('media_brand') && !['sports-news', 'football', 'business-news', 'entertainment-shows', 'music'].includes(primary)) {
      others = [primary, ...others].filter((s) => s && s !== 'national-news');
      primary = TV_NAME.test(r.name) ? 'tv-radio' : 'national-news';
      if (primary === 'tv-radio') others.unshift('national-news');
      reason += '; media brand -> news first';
    } else if (r.rails.includes('individual') && primary === 'politics') {
      primary = 'political-analysis'; others = ['politics', ...others];
      reason += '; individual commentator';
    }
    if (!primary) { primary = hits[0] || 'news-current-affairs'; reason += '; no current category, keyword guess'; }
  } else if (hits[0] === 'radio-stations') {
    primary = 'radio-stations'; others = ['national-news']; confidence = 'high'; reason = 'name/description says radio/FM';
  } else if (r.topics.includes('business')) {
    primary = 'business-news'; others = ['tv-radio']; confidence = 'high'; reason = 'topic business';
  } else if (r.topics.includes('politics')) {
    primary = 'politics'; others = ['political-analysis']; confidence = 'medium'; reason = 'topic politics';
  } else if (r.topics.includes('culture')) {
    primary = hits.includes('music') ? 'music' : 'african-culture'; confidence = 'medium'; reason = 'topic culture';
  } else if (r.rails.includes('live_now') && (INTERNATIONAL.test(r.name) || multi)) {
    primary = 'international-affairs'; others = ['tv-radio', 'breaking-news']; confidence = 'high';
    reason = `24 h news rail; ${INTERNATIONAL.test(r.name) ? 'international broadcaster' : 'curated in several countries'}`;
  } else if (r.rails.includes('live_now') || r.rails.includes('national_tv')) {
    // These rails hold national outlets of every kind (TV, newspapers, news sites): national news first, TV only
    // when the name says so.
    const tv = TV_NAME.test(r.name);
    primary = tv ? 'tv-radio' : 'national-news'; others = tv ? ['national-news'] : [];
    confidence = tv ? 'high' : 'medium';
    reason = `rail ${r.rails.join(',')} (national outlet${tv ? ', TV in the name' : ', not named as TV - check'})`;
  } else if (r.rails.includes('africa_voices')) {
    primary = 'independent-media'; others = ['news-current-affairs']; confidence = 'medium'; reason = 'rail africa_voices (pan-African independent voices)';
  } else if (r.rails.includes('local_voices')) {
    primary = 'independent-media'; others = ['news-current-affairs']; confidence = 'low'; reason = 'rail local_voices (local independent voices) - check';
  } else {
    primary = 'news-current-affairs'; reason = 'no rail/topic signal';
  }
  for (const h of hits) if (h !== primary && !others.includes(h) && h !== 'radio-stations') others.push(h);
  if (hits.length && r.kind === 'VC') reason += `; keywords: ${hits.join(',')}`;
  others = others.filter((s) => subs.has(s)).slice(0, 3);
  if (!subs.has(primary)) throw new Error(`unknown proposed slug ${primary} for ${r.name}`);
  return { primary, others, confidence, reason };
}

const csv = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const out = [['kind', 'key', 'name', 'countries', 'rails_or_kind', 'topics', 'current_categories', 'proposed_main_category',
  'proposed_primary_subcategory', 'proposed_other_subcategories', 'confidence', 'reason', 'description', 'owner_decision (ok / slug;slug / reject)'].map(csv).join(',')];
const stats = {}; const conf = {};
for (const r of rows) {
  const p = propose(r);
  stats[p.primary] = (stats[p.primary] || 0) + 1;
  conf[p.confidence] = (conf[p.confidence] || 0) + 1;
  out.push([r.kind === 'VC' ? 'channel' : 'creator', r.key, r.name, r.countries, r.rails.join(','), r.topics.join(','), r.current,
    nameOf(subs.get(p.primary).parent), p.primary, p.others.join(';'), p.confidence, p.reason, r.descr, ''].map(csv).join(','));
}
fs.writeFileSync(path.join(__dirname, 'classification.csv'), '﻿' + out.join('\r\n') + '\r\n');
console.log(`rows ${rows.length} (channels ${rows.filter((r) => r.kind === 'VC').length}, creators ${rows.filter((r) => r.kind === 'CR').length})`);
console.log('confidence', conf);
console.log('primary', Object.entries(stats).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', '));
