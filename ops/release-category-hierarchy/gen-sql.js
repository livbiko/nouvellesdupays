// CR-2026-11-17-02: writes db/migrations/020_category_hierarchy.sql, and rehearse.sql / apply.sql / reverse.sql here,
// from tree.js and before-categories.txt (the 49 rows as they were, id|slug|parent|name_en|name_fr|sort_order).
// Usage: node gen-sql.js
const fs = require('fs');
const path = require('path');
const tree = require('./tree');

const here = __dirname;
const root = path.resolve(here, '..', '..');
const before = fs.readFileSync(path.join(here, 'before-categories.txt'), 'utf8').trim().split(/\r?\n/).map((l) => {
  const [id, slug, parent, nameEn, nameFr, sort] = l.split('|');
  return { id: +id, slug, parent: parent || null, nameEn, nameFr, sort: +sort };
});
if (before.length !== 49) throw new Error(`expected 49 categories before, got ${before.length}`);
const existing = new Set(before.map((b) => b.slug));
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const nodes = []; // { slug, parent, en, fr, sort, from }
tree.forEach(([slug, fr, en, from, children], i) => {
  nodes.push({ slug, parent: null, en, fr, sort: (i + 1) * 100, from });
  children.forEach(([s, cfr, cen, cfrom], j) => nodes.push({ slug: s, parent: slug, en: cen, fr: cfr, sort: (i + 1) * 100 + j + 1, from: cfrom }));
});
for (const n of nodes) {
  if (n.from && n.from !== n.slug) throw new Error(`renamed slug not supported: ${n.from} -> ${n.slug}`);
  if (n.from && !existing.has(n.slug)) throw new Error(`${n.slug} marked as kept but does not exist`);
  if (!n.from && existing.has(n.slug)) throw new Error(`${n.slug} marked as new but exists`);
}
const inTree = new Set(nodes.map((n) => n.slug));
const off = before.filter((b) => !inTree.has(b.slug)).map((b) => b.slug);
const newTops = nodes.filter((n) => !n.parent && !n.from);
const kept = nodes.filter((n) => n.from);
const newSubs = nodes.filter((n) => n.parent && !n.from);
if (nodes.length !== 78 || newSubs.length + kept.filter((n) => n.parent).length !== 70) throw new Error('tree is not 8 + 70');

const values = (list) => list.map((n) => `  (${q(n.slug)}, ${q(n.parent)}, ${q(n.en)}, ${q(n.fr)}, ${n.sort})`).join(',\n');

const migration = `-- 020: category hierarchy from the owner's brief (CR-2026-11-17-02, 11-18): 8 main categories, 70 subcategories,
-- French names on the site. Additive: no category and no link is deleted; categories with no place in the brief are
-- switched off (active = false, hidden on the site, a link to one counts for its parent). Generated by
-- ops/release-category-hierarchy/gen-sql.js from tree.js.
-- Also: video_channel_category_links (a /youtube directory channel's subcategories; channel_key = the YouTube channel
-- id, or the lowercased channel/page URL - the directory's grouping, so a channel curated in several countries is one
-- record) and channel_metrics (subscribers / views / video count of directory channels that have no social_accounts
-- row; append-only like audience_metrics).

ALTER TABLE creator_categories ADD COLUMN IF NOT EXISTS active BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE creator_categories ADD COLUMN IF NOT EXISTS description_fr TEXT;
ALTER TABLE creator_categories ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();
CREATE INDEX IF NOT EXISTS idx_creator_categories_parent ON creator_categories (parent_slug, sort_order);
CREATE INDEX IF NOT EXISTS idx_creator_category_links_category ON creator_category_links (category_id);

-- The restructure runs once: migrate.js re-runs every file, and names, order and active flags edited later on
-- /admin/categories must survive it. 'politics-society' is one of the two new main categories.
DO $restructure$
BEGIN
  IF EXISTS (SELECT 1 FROM creator_categories WHERE slug = 'politics-society') THEN
    RETURN;
  END IF;
  INSERT INTO creator_categories (slug, parent_slug, name_en, name_fr, sort_order) VALUES
${values(newTops)};
${kept.map((n) => `  UPDATE creator_categories SET parent_slug = ${q(n.parent)}, name_en = ${q(n.en)}, name_fr = ${q(n.fr)}, sort_order = ${n.sort}, updated_at = now() WHERE slug = ${q(n.slug)};`).join('\n')}
  INSERT INTO creator_categories (slug, parent_slug, name_en, name_fr, sort_order) VALUES
${values(newSubs)}
  ON CONFLICT (slug) DO NOTHING;
  UPDATE creator_categories SET active = false, updated_at = now() WHERE slug IN (${off.map(q).join(', ')});
END
$restructure$;

CREATE TABLE IF NOT EXISTS video_channel_category_links (
  channel_key  TEXT NOT NULL CHECK (channel_key <> ''),
  category_id  INTEGER NOT NULL REFERENCES creator_categories(id),
  is_primary   BOOLEAN NOT NULL DEFAULT false,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (channel_key, category_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_vc_category_primary ON video_channel_category_links (channel_key) WHERE is_primary;
CREATE INDEX IF NOT EXISTS idx_vc_category_links_category ON video_channel_category_links (category_id);

CREATE TABLE IF NOT EXISTS channel_metrics (
  id           BIGSERIAL PRIMARY KEY,
  channel_key  TEXT NOT NULL CHECK (channel_key <> ''),
  metric       TEXT NOT NULL CHECK (metric IN ('subscribers', 'total_views', 'video_count')),
  value        BIGINT NOT NULL CHECK (value >= 0),
  source       TEXT NOT NULL DEFAULT 'youtube_data_api',
  measured_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_channel_metrics_latest ON channel_metrics (channel_key, metric, measured_at DESC);
`;
fs.writeFileSync(path.join(root, 'db', 'migrations', '020_category_hierarchy.sql'), migration);

const checks = `\\echo ===AFTER===
SELECT count(*) AS categories, count(*) FILTER (WHERE active) AS active,
       count(*) FILTER (WHERE active AND parent_slug IS NULL) AS active_main,
       count(*) FILTER (WHERE active AND parent_slug IS NOT NULL) AS active_sub FROM creator_categories;
SELECT count(*) AS old_slugs_present FROM creator_categories WHERE slug IN (${before.map((b) => q(b.slug)).join(', ')});
SELECT count(*) AS links, count(*) FILTER (WHERE cc.id IS NULL) AS broken FROM creator_category_links l LEFT JOIN creator_categories cc ON cc.id = l.category_id;
SELECT count(*) AS subs_without_active_parent FROM creator_categories c
 WHERE c.parent_slug IS NOT NULL AND c.active AND NOT EXISTS (SELECT 1 FROM creator_categories p WHERE p.slug = c.parent_slug AND p.active AND p.parent_slug IS NULL);
SELECT slug, active FROM creator_categories WHERE slug IN (${off.map(q).join(', ')}) ORDER BY 1;
SELECT to_regclass('video_channel_category_links') AS vc_links, to_regclass('channel_metrics') AS channel_metrics;
`;
const head = (what) => `-- CR-2026-11-17-02: migration 020 on production. ${what}
-- Middle part = db/migrations/020_category_hierarchy.sql verbatim (generated by gen-sql.js).
\\set ON_ERROR_STOP on
SET lock_timeout = '10s';
SET statement_timeout = '60s';
BEGIN;
`;
fs.writeFileSync(path.join(here, 'rehearse.sql'), `${head('Rehearsal: rolled back.')}${migration}\n${checks}ROLLBACK;\n`);
fs.writeFileSync(path.join(here, 'apply.sql'), `${head('Apply.')}${migration}\n${checks}COMMIT;\n`);

const reverse = `-- Reverse CR-2026-11-17-02 / migration 020: restores the 49 categories exactly as before-categories.txt, removes the
-- categories the migration added (and any link to them - they did not exist before), drops the new tables (channel
-- classifications and channel_metrics are lost) and columns. Revert the 020 commit too, or migrate.js re-applies it.
\\set ON_ERROR_STOP on
SET lock_timeout = '10s';
BEGIN;
DROP TABLE IF EXISTS channel_metrics;
DROP TABLE IF EXISTS video_channel_category_links;
${before.map((b) => `UPDATE creator_categories SET parent_slug = ${q(b.parent)}, name_en = ${q(b.nameEn)}, name_fr = ${q(b.nameFr)}, sort_order = ${b.sort} WHERE slug = ${q(b.slug)};`).join('\n')}
DELETE FROM creator_category_links WHERE category_id IN (SELECT id FROM creator_categories WHERE slug NOT IN (${before.map((b) => q(b.slug)).join(', ')}));
DELETE FROM creator_categories WHERE parent_slug IS NOT NULL AND slug NOT IN (${before.map((b) => q(b.slug)).join(', ')});
DELETE FROM creator_categories WHERE slug NOT IN (${before.map((b) => q(b.slug)).join(', ')});
DROP INDEX IF EXISTS idx_creator_categories_parent;
DROP INDEX IF EXISTS idx_creator_category_links_category;
ALTER TABLE creator_categories DROP COLUMN IF EXISTS updated_at;
ALTER TABLE creator_categories DROP COLUMN IF EXISTS description_fr;
ALTER TABLE creator_categories DROP COLUMN IF EXISTS active;
SELECT count(*) AS categories FROM creator_categories;
COMMIT;
`;
fs.writeFileSync(path.join(here, 'reverse.sql'), reverse);
console.log(`nodes ${nodes.length}: new main ${newTops.length}, kept ${kept.length}, new sub ${newSubs.length}, off ${off.length} (${off.join(', ')})`);
