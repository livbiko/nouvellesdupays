# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql: third batch from the 2026-10-17 stale sweep.
#  - Centrafrique-Presse (219): centrafrique-presse.com hijacked -- now "Gaming and Playing", an Indonesian gambling blog
#    (feed newest 2024-02-05, posts about "judi"). RJDH (221): rjdh.org hijacked -- now an SEO site about journalism
#    concepts, newest post 2024-12-27. Both flagged in earlier notes but never actioned -> feed_status 'unavailable'.
#    0 articles from either in the last 120 days (stale sweep); older ones are checked by the guard below.
#  - Le Patriote (7291): its sitemap.xml stopped updating 2025-08-01 (28k URLs) and the site has no feed, while the homepage
#    is current. Moves to the html crawler on the homepage with the default article heuristic (same as the dry run:
#    10 fetched, 7 current dated articles, 3 older ones dropped by the 14-day filter). robots.txt allows all.
# Every statement is guarded; the transaction aborts unless each touches exactly the expected rows.

HIJACKED = [(219, 'Centrafrique-Presse', 'centrafrique-presse.com'), (221, 'RJDH', 'rjdh.org')]
LP = 7291
LP_OLD = 'https://lepatriote.ci/sitemap.xml'
LP_NEW = 'https://lepatriote.ci/'
FREQ = 60


def dq(s):
    assert '$$' not in s
    return f'$${s}$$'


steps = ''
for pid, name, dom in HIJACKED:
    steps += f"""  IF EXISTS (SELECT 1 FROM articles WHERE publisher_id = {pid} AND fetched_at > DATE '2024-01-01') THEN
    RAISE EXCEPTION '{name}: articles fetched since 2024 exist - check them for hijacked content first - nothing changed'; END IF;
  UPDATE publishers SET feed_status = 'unavailable' WHERE id = {pid} AND name = {dq(name)} AND feed_status = 'active';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: not the active {name} - nothing changed'; END IF;
"""
steps += f"""  IF NOT EXISTS (SELECT 1 FROM publishers WHERE id = {LP} AND name = 'Le Patriote' AND feed_status = 'active') THEN
    RAISE EXCEPTION 'publisher {LP} is not the active Le Patriote - nothing changed'; END IF;
  IF (SELECT count(*) FROM feeds WHERE publisher_id = {LP}) <> 1 THEN RAISE EXCEPTION 'Le Patriote has other sources - nothing changed'; END IF;
  IF EXISTS (SELECT 1 FROM feeds WHERE feed_url = '{LP_NEW}') THEN RAISE EXCEPTION 'a source with the new URL already exists - nothing changed'; END IF;
  UPDATE feeds SET enabled = false WHERE publisher_id = {LP} AND feed_url = '{LP_OLD}' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'Le Patriote old sitemap source: % rows, expected 1 - nothing changed', k; END IF;
  INSERT INTO feeds (publisher_id, feed_url, feed_type, crawl_frequency_minutes, enabled, respect_robots_txt,
                     allowed_domains, category_urls, article_url_patterns, parser_config)
  VALUES ({LP}, '{LP_NEW}', 'html', {FREQ}, true, true, ARRAY['lepatriote.ci']::text[], '{{}}', '{{}}', '{{}}'::jsonb);
"""

BODY = f"""SET lock_timeout = '5s';
BEGIN;
SELECT 'before|' || p.id || '|' || p.feed_status || '|articles=' || (SELECT count(*) FROM articles a WHERE a.publisher_id = p.id)
  || '|newest_fetch=' || coalesce((SELECT max(fetched_at)::date::text FROM articles a WHERE a.publisher_id = p.id), '-') FROM publishers p WHERE p.id IN (219, 221, {LP}) ORDER BY p.id;
SELECT 'beforefeed|' || id || '|' || feed_type || '|' || enabled || '|' || feed_url FROM feeds WHERE publisher_id = {LP} ORDER BY id;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'after|' || p.id || '|' || p.feed_status FROM publishers p WHERE p.id IN (219, 221) ORDER BY p.id;
SELECT 'after|' || id || '|' || feed_type || '|' || enabled || '|' || coalesce(crawl_frequency_minutes::text, '-') || '|' || feed_url FROM feeds WHERE publisher_id = {LP} ORDER BY id;"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Stale sweep batch 3: 2 hijacked publishers unavailable, Le Patriote to the html crawler (data only). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || id || '|' || feed_status FROM publishers WHERE id IN (219, 221, {LP}) ORDER BY id;\n")
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: the 2 publishers back to active, Le Patriote back to its sitemap source (crawled source disabled, kept). Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
  UPDATE publishers SET feed_status = 'active' WHERE id IN (219, 221) AND feed_status = 'unavailable';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 2 THEN RAISE EXCEPTION 'publishers: % rows, expected 2', k; END IF;
  UPDATE feeds SET enabled = false WHERE publisher_id = {LP} AND feed_url = '{LP_NEW}' AND feed_type = 'html' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'crawled source: % rows, expected 1', k; END IF;
  UPDATE feeds SET enabled = true WHERE publisher_id = {LP} AND feed_url = '{LP_OLD}' AND NOT enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'old source: % rows, expected 1', k; END IF;
END $do$;
COMMIT;
""")
