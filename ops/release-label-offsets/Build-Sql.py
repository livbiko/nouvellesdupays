# Build #105 - label_utc_offset_hours on five feeds whose dates run ahead of the clock (data only, MEDIUM).
# Generates apply.sql, rehearse.sql, reverse.sql, verify.sql.
# 2026-10-19: 14 RSS feeds had (almost) every article of the last 3 days stored at its fetch time - the future-date guard
# clamps items dated ahead of now. Each feed parsed with the worker's rss-parser and every item's lead over the clock measured.
# Applied only where the lead is consistent with the country's UTC offset AND the country has no DST change ahead:
#   Tuoi Tre (987, VN +7, no zone in the date)  -> 7   all 50 items ahead, newest +6.1 h in a UTC process
#   Delfino.cr (1528, CR, UTC written as -0600)  -> 6   15/21 ahead, newest +5.8 h
#   Jordan News (1050, JO +3, local as GMT)      -> 3   newest +2.0 h, hourly posts
#   Punch (6, NG +1, local as +0000)             -> 1   newest +0.9 h
#   ActuCameroun (212, CM +1, local as +0000)    -> 1   newest +0.9 h
# Held back: Cairo 24 (EG, DST ends 2026-10-29), Dnevni Avaz and FENA (BA, DST ends 2026-10-25) - a fixed offset would be
# wrong in days; need a time-zone-aware option. Left alone (only some items ahead, ambiguous): Jerusalem Post, Daily Maverick,
# RTP Noticias, Jeune Afrique. Existing clamped rows are left as they are (fetch time is within minutes of publication).
import json

FEEDS = [  # publisher_id, feed_url, offset
    (987, 'https://tuoitre.vn/rss/tin-moi-nhat.rss', 7),
    (1528, 'https://delfino.cr/feed', 6),
    (1050, 'https://www.jordannews.jo/rss', 3),
    (6, 'https://punchng.com/feed/', 1),
    (212, 'https://actucameroun.com/feed/', 1),
]
IDS = ', '.join(str(p) for p, _, _ in FEEDS)
HDR = '\\set ON_ERROR_STOP on\n'


def q(s):
    return "'" + s.replace("'", "''") + "'"


steps = ''
for pid, url, off in FEEDS:
    steps += f"""  UPDATE feeds SET parser_config = '{{"label_utc_offset_hours": {off}}}'::jsonb
   WHERE publisher_id = {pid} AND feed_url = {q(url)} AND feed_type = 'rss' AND enabled AND parser_config = '{{}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % feed rows with an empty parser_config, expected 1 - nothing changed', k; END IF;
"""
BODY = f"""SET lock_timeout = '5s';
BEGIN;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'config|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;"""

with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Build #105 label_utc_offset_hours on five feeds (data only, MEDIUM). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n'
             f"SELECT 'rolledback|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;\n")
rev = ''.join(f"""  UPDATE feeds SET parser_config = '{{}}'::jsonb WHERE publisher_id = {pid} AND parser_config = '{{"label_utc_offset_hours": {off}}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
""" for pid, _, off in FEEDS)
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: parser_config back to '{{}}'. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
{rev}END $do$;
COMMIT;
SELECT 'reversed|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;
""")
with open('verify.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Read-only, ~30 min after apply. Rows fetched since then should no longer sit at their fetch time, nor after it.
SELECT 'new|' || a.publisher_id || '|' || count(*) || ' new|' || count(*) FILTER (WHERE abs(extract(epoch FROM a.published_at - a.fetched_at)) < 5) || ' at fetch time|'
       || count(*) FILTER (WHERE a.published_at > a.fetched_at) || ' after fetch|newest ' || coalesce(to_char(max(a.published_at), 'HH24:MI'), '-') || ' (fetched ' || coalesce(to_char(max(a.fetched_at), 'HH24:MI'), '-') || ')'
  FROM articles a WHERE a.publisher_id IN ({IDS}) AND a.fetched_at > now() - interval '30 minutes' GROUP BY a.publisher_id ORDER BY 1;
""")
print('ok', len(FEEDS))
