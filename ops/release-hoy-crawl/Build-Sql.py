# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql: Hoy.com.py (1560) moves from RSS to the html crawler.
# Hoy's RSS feed (/rss and /feed) is frozen at 2023-12-31 and it has no sitemap (sitemap_index.xml 404), while the site is
# current. Its article titles all start "Diario HOY | ", stripped by the new worker option parser_config.title_prefix
# (branch feat/hoy-title-prefix; Run-Release.ps1 deploys the worker before this data). Dates come from standard meta.
# Dry-run 2026-10-17 with this exact config: 45 candidates, 20 fetched in 31 s, 20/20 current dated articles, clean
# headlines. robots.txt allows all agents except search/ajax paths. Same shape as release-xinhua-crawl.
import json

PID = 1560
NAME = 'Hoy.com.py'
OLD_URL = 'https://www.hoy.com.py/rss'
NEW_URL = 'https://www.hoy.com.py/'
CATEGORY_URLS = ['https://www.hoy.com.py/nacionales', 'https://www.hoy.com.py/politica', 'https://www.hoy.com.py/mundo']
PATTERNS = ['*/2026/*', '*/2027/*']
DOMAINS = ['hoy.com.py']
PARSER_CONFIG = {'title_prefix': 'Diario HOY | '}
FREQ = 30  # minutes; up to CRAWL_MAX_ARTICLES_PER_RUN (20) article pages per run, 1 s apart
def arr(xs):
    return "ARRAY[" + ", ".join(f"'{x}'" for x in xs) + "]::text[]"


BODY = f"""SET lock_timeout = '5s';
BEGIN;
SELECT 'before|' || id || '|' || feed_type || '|' || enabled || '|' || feed_url FROM feeds WHERE publisher_id = {PID} ORDER BY id;
DO $do$
DECLARE k int;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM publishers WHERE id = {PID} AND name = '{NAME}' AND feed_status = 'active') THEN
    RAISE EXCEPTION 'publisher {PID} is not the active {NAME} - nothing changed'; END IF;
  IF (SELECT count(*) FROM feeds WHERE publisher_id = {PID}) <> 1 THEN
    RAISE EXCEPTION '{NAME} has other sources - nothing changed'; END IF;
  IF EXISTS (SELECT 1 FROM feeds WHERE feed_url = '{NEW_URL}') THEN
    RAISE EXCEPTION 'a source with the new URL already exists - nothing changed'; END IF;
  UPDATE feeds SET enabled = false WHERE publisher_id = {PID} AND feed_url = '{OLD_URL}' AND feed_type = 'rss' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'old RSS feed: % rows, expected 1 - nothing changed', k; END IF;
  INSERT INTO feeds (publisher_id, feed_url, feed_type, crawl_frequency_minutes, enabled, respect_robots_txt,
                     allowed_domains, category_urls, article_url_patterns, parser_config)
  VALUES ({PID}, '{NEW_URL}', 'html', {FREQ}, true, true, {arr(DOMAINS)}, {arr(CATEGORY_URLS)}, {arr(PATTERNS)}, '{json.dumps(PARSER_CONFIG)}'::jsonb);
END $do$;
SELECT 'after|' || id || '|' || feed_type || '|' || enabled || '|' || coalesce(crawl_frequency_minutes::text, '-') || '|' || feed_url
  || '|' || coalesce(array_length(category_urls, 1), 0) || ' listing|' || coalesce(array_length(article_url_patterns, 1), 0) || ' patterns' FROM feeds WHERE publisher_id = {PID} ORDER BY id;"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- {NAME} ({PID}): frozen RSS -> html crawler (data only). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || id || '|' || feed_type || '|' || enabled FROM feeds WHERE publisher_id = {PID} ORDER BY id;\n")
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: disable the crawled source (kept, with its articles) and re-enable the old RSS feed. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
  UPDATE feeds SET enabled = false WHERE publisher_id = {PID} AND feed_url = '{NEW_URL}' AND feed_type = 'html' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'crawled source: % rows, expected 1', k; END IF;
  UPDATE feeds SET enabled = true WHERE publisher_id = {PID} AND feed_url = '{OLD_URL}' AND NOT enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'old RSS feed: % rows, expected 1', k; END IF;
END $do$;
COMMIT;
""")
print('ok')



