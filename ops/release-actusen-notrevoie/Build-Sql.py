# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql for the Actusen / Notre Voie fix:
#  - Actusen (8905): actusen.com was taken over by an unrelated French lifestyle site; the outlet now lives at actusen.sn.
#    Point the feed and homepage at actusen.sn, and add its editorial profile.
#  - Notre Voie (8894): domain parked (sitemap lists only /lander) -> feed_status 'unavailable', like Build #68.
# Every UPDATE is guarded on the current value; the transaction aborts unless each touches exactly one row.
#  - Delete the 13 articles ingested from the hijacked actusen.com (French lifestyle content shown under Senegal).
