# Generates apply / rehearse / reverse SQL for Build #141: Capital News (GW), an HTML-crawled source.
# Owner, 2026-11-03: "yes, add Capital News". Guinea-Bissau had 4 live publishers (West Africa target 5).
# No RSS; its sitemap lags ~4 days, so the homepage is crawled as a listing page (dry crawl 2026-11-03:
# ids 1969-1972 with correct titles and dates). Same shape as release-caribbean-sources (Build #132).
import json, os

TAG = '[added by Claude 2026-11-03, Capital News GW]'
DAY = '2026-11-03'


def q(s):
    return "'" + s.replace("'", "''") + "'"


P = dict(iso='GW', name='Capital News', slug='capital-news', home='https://www.capitalnews.gw/', dom='capitalnews.gw',
         lang='pt', st='ONLINE_NEWS',
         patterns=['/artigos?slug=*&id=*'],
         parser={'date_after_label': '<h6 class="text-primary">', 'date_format': 'DD-MM-YYYY', 'utc_offset': '+00:00'},
         check='HTML listing (homepage), dry crawl 4/4 articles dated 2026-11-01..03, robots.txt allows all',
         desc='Digital newspaper based in Bissau, Guinea-Bissau, founded in 2020.',
         own='Presse en ligne privée', owner='CAPITAL MÍDIA Sarl', tags=['independent'],
         hist="Journal numérique basé à Bissau, créé le 26 juin 2020, propriété de la société CAPITAL MÍDIA Sarl.",
         cur="Actualité politique, judiciaire et sociale bissau-guinéenne en portugais (élections, droits humains, éducation).",
         ev="Se présente comme une publication en ligne indépendante et apartidaire (page « Sobre nós »). Indépendance non vérifiée de façon externe pour ce profil.",
         src=[('https://www.capitalnews.gw/artigos?slug=principios', 'Page « Sobre nós » : Capital News', 'self_description')])

p = P
srcs = json.dumps([dict(url=u, note=n, category=c, accessed_at=DAY) for u, n, c in p['src']], ensure_ascii=False)
detail = f"Added on owner approval {DAY} (GW at 4 live publishers); {p['check']} {TAG}"
tags = ','.join(q(t) for t in p['tags'])
pats = ','.join(q(x) for x in p['patterns'])
parser = json.dumps(p['parser'], ensure_ascii=False)

apply = f"""-- GENERATED by Build-Sql.py. Build #141 (MEDIUM): Capital News (GW), crawled from its homepage (feed_type html).
\\set ON_ERROR_STOP on
SET lock_timeout = '10s';
BEGIN;
DO $do$
DECLARE v_pid integer; v_sid integer; v_cid integer;
BEGIN
  IF EXISTS (SELECT 1 FROM publishers WHERE slug = {q(p['slug'])} OR domain = {q(p['dom'])})
     OR EXISTS (SELECT 1 FROM feeds WHERE feed_url = {q(p['home'])}) THEN
    RAISE EXCEPTION 'Capital News is already present - nothing changed';
  END IF;
  SELECT id INTO v_cid FROM countries WHERE iso_code = {q(p['iso'])};
  INSERT INTO publisher_submissions (name, homepage_url, feed_url, feed_type, country_id, language, feed_verified,
    verification_detail, domain, ingestion_method, category_urls, article_url_patterns, status, status_changed_at, reviewed_at)
  VALUES ({q(p['name'])}, {q(p['home'])}, NULL, NULL, v_cid, {q(p['lang'])}, true,
    {q(detail)}, {q(p['dom'])}, 'html', '{{}}'::text[], ARRAY[{pats}]::text[], 'approved', now(), now()) RETURNING id INTO v_sid;
  INSERT INTO publishers (country_id, name, homepage_url, feed_status, language, domain, source_type, slug, creator_kind, description)
  VALUES (v_cid, {q(p['name'])}, {q(p['home'])}, 'active', {q(p['lang'])}, {q(p['dom'])}, {q(p['st'])}, {q(p['slug'])}, 'organisation', {q(p['desc'])})
  RETURNING id INTO v_pid;
  INSERT INTO feeds (publisher_id, feed_url, feed_type, crawl_frequency_minutes, allowed_domains, respect_robots_txt,
    category_urls, article_url_patterns, parser_config)
  VALUES (v_pid, {q(p['home'])}, 'html', 60, ARRAY[{q(p['dom'])}]::text[], true,
    '{{}}'::text[], ARRAY[{pats}]::text[], {q(parser)}::jsonb);
  UPDATE publisher_submissions SET publisher_id = v_pid WHERE id = v_sid;
  INSERT INTO editorial_profiles (publisher_id, ownership_type, owner, classification_tags, political_party_association,
    historical_context, current_context, confidence, evidence_summary, evidence_sources,
    classification_date, last_reviewed, evidence_date, review_required)
  VALUES (v_pid, {q(p['own'])}, {q(p['owner'])}, ARRAY[{tags}]::text[], NULL,
    {q(p['hist'])}, {q(p['cur'])}, 'low', {q(p['ev'])}, {q(srcs)}::jsonb,
    '{DAY}', '{DAY}', '{DAY}', true);
  RAISE NOTICE '% added: publisher %', {q(p['name'])}, v_pid;
END $do$;
SELECT p.id, p.slug, c.iso_code, f.id AS feed_id, f.feed_type, f.feed_url, f.article_url_patterns, f.parser_config
  FROM publishers p JOIN countries c ON c.id = p.country_id JOIN feeds f ON f.publisher_id = p.id WHERE p.slug = {q(p['slug'])};
SELECT owner, historical_context FROM editorial_profiles e JOIN publishers p ON p.id = e.publisher_id WHERE p.slug = {q(p['slug'])};
COMMIT;
"""

reverse = f"""-- GENERATED by Build-Sql.py. Reverses Build #141 (all tables with a FK to publishers, children first).
\\set ON_ERROR_STOP on
BEGIN;
DO $do$
DECLARE pids integer[];
BEGIN
  SELECT array_agg(id) INTO pids FROM publishers WHERE slug = {q(p['slug'])} AND domain = {q(p['dom'])};
  IF pids IS NULL THEN RAISE NOTICE 'Nothing to reverse'; RETURN; END IF;
  DELETE FROM articles              WHERE publisher_id = ANY(pids);
  DELETE FROM audience_metrics      WHERE social_account_id IN (SELECT id FROM social_accounts WHERE publisher_id = ANY(pids));
  DELETE FROM social_accounts       WHERE publisher_id = ANY(pids);
  DELETE FROM youtube_videos        WHERE publisher_id = ANY(pids);
  DELETE FROM youtube_channels      WHERE publisher_id = ANY(pids);
  DELETE FROM contacts              WHERE publisher_id = ANY(pids);
  DELETE FROM discovery_mining_log  WHERE publisher_id = ANY(pids);
  UPDATE discovered_sources SET discovered_from_publisher_id = NULL WHERE discovered_from_publisher_id = ANY(pids);
  DELETE FROM source_scores         WHERE publisher_id = ANY(pids);
  DELETE FROM editorial_profiles    WHERE publisher_id = ANY(pids);
  DELETE FROM feeds                 WHERE publisher_id = ANY(pids);
  DELETE FROM publisher_submissions WHERE publisher_id = ANY(pids) OR verification_detail LIKE {q('%' + TAG + '%')};
  DELETE FROM publishers            WHERE id = ANY(pids);
  RAISE NOTICE 'Reversed: removed % publishers', array_length(pids, 1);
END $do$;
COMMIT;
"""

here = os.path.dirname(os.path.abspath(__file__))
for name, text in (('apply.sql', apply), ('rehearse.sql', apply.replace('\nCOMMIT;\n', '\nROLLBACK;\n')), ('reverse.sql', reverse)):
    with open(os.path.join(here, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
print('written: apply.sql rehearse.sql reverse.sql')
