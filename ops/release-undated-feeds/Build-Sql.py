# Generates apply.sql, rehearse.sql and reverse.sql: 5 RSS feeds whose items carry no usable date.
# 2026-10-17: every article of these publishers is stored with published_at NULL, so none ever appears in "latest" lists
# (NULLS LAST / date-window filters). Hankyoreh, Le Parisien, Press TV and Kathmandu Post items have no date element at
# all; El Khabar's pubDate is "21:10 | 17-10-2026", which does not parse.
#  A. One guarded transaction: parser_config {"undated": "fetch_time"} on the 5 feeds -- the existing per-feed option
#     (Build #69, The Baltic Times): an undated item gets the time it was first seen, one minute earlier per feed position.
#     Feeds are polled every 5 minutes, so that is within minutes of publication. Only new items are affected.
#  B. Backfill, autocommit batches of 500 + 4 s pause, lock-waiter stop (template: release-categorize-urlsec):
#     undated rows of these publishers fetched in the last 14 days (the window "latest" lists can show) get
#     published_at = fetched_at. Older undated rows are left as they are.
# Reverse: A restores parser_config '{}'; B sets published_at back to NULL where published_at = fetched_at exactly
# (rows stored by the worker with fetch_time never match: their time is taken before the insert).

FEEDS = [  # publisher_id, name, feed_url
    (968, 'The Hankyoreh', 'https://www.hani.co.kr/rss/'),
    (3138, 'Le Parisien', 'https://feeds.leparisien.fr/leparisien/rss'),
    (1047, 'Press TV', 'https://www.presstv.ir/rss.xml'),
    (1015, 'Kathmandu Post', 'https://kathmandupost.com/rss'),
    (171, 'El Khabar', 'https://www.elkhabar.com/feed'),
]
IDS = ', '.join(str(f[0]) for f in FEEDS)
WINDOW = "now() - interval '14 days'"

steps = ''
for pid, name, url in FEEDS:
    steps += f"""  UPDATE feeds SET parser_config = '{{"undated": "fetch_time"}}'::jsonb
   WHERE publisher_id = {pid} AND feed_url = '{url}' AND feed_type = 'rss' AND enabled AND parser_config = '{{}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % feed rows with an empty parser_config, expected 1 - nothing changed', k; END IF;
"""

PART_A = f"""SET lock_timeout = '5s';
BEGIN;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'config|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;"""

COUNT = f"""SELECT 'undated|' || publisher_id || '|' || count(*) || '|in window=' || count(*) FILTER (WHERE fetched_at > {WINDOW})
  FROM articles WHERE publisher_id IN ({IDS}) AND published_at IS NULL GROUP BY publisher_id ORDER BY publisher_id;"""

PART_B = f"""CREATE TEMP TABLE batch_ids AS
  SELECT id, ((row_number() OVER (ORDER BY id)) - 1) / 500 AS b FROM articles
   WHERE publisher_id IN ({IDS}) AND published_at IS NULL AND fetched_at > {WINDOW};
CREATE INDEX ON batch_ids (b); ANALYZE batch_ids;
SELECT 'batches|' || count(*) || ' rows|' || coalesce(max(b) + 1, 0) || ' batches' FROM batch_ids;
SELECT 'start|' || clock_timestamp();
SET statement_timeout = '15s';
SELECT 'DO $w$ BEGIN IF EXISTS (SELECT 1 FROM pg_stat_activity WHERE datname = current_database() AND pid <> pg_backend_pid() AND wait_event_type = ''Lock'' AND now() - query_start > interval ''30 seconds'') THEN RAISE EXCEPTION ''stopping: a session has waited on a lock for over 30s''; END IF; END $w$',
       format('UPDATE articles a SET published_at = a.fetched_at FROM batch_ids i WHERE i.b = %s AND a.id = i.id AND a.published_at IS NULL', b),
       'SELECT pg_sleep(4)'
  FROM generate_series(0, coalesce((SELECT max(b) FROM batch_ids), -1)) b ORDER BY b
\\gexec
RESET statement_timeout;
SELECT 'end|' || clock_timestamp();"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Undated feeds: parser_config undated=fetch_time on 5 feeds (A), then a batched 14-day backfill (B). Generated by Build-Sql.py.\n"
             f"-- B runs in autocommit batches: never wrap this file in BEGIN. Reverse: reverse.sql.\n{HDR}{COUNT}\n{PART_A}\nCOMMIT;\n{PART_B}\n{COUNT}\n")
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal: part A in a rolled-back transaction, and part B's row and batch counts only (no update). Generated by Build-Sql.py.\n"
             f"{HDR}{COUNT}\n{PART_A}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || publisher_id || '|' || parser_config::text FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;\n"
             f"SELECT 'would-backfill|' || count(*) || ' rows|' || ceil(count(*) / 500.0) || ' batches' FROM articles WHERE publisher_id IN ({IDS}) AND published_at IS NULL AND fetched_at > {WINDOW};\n")
rev = ''
for pid, name, url in FEEDS:
    rev += f"""  UPDATE feeds SET parser_config = '{{}}'::jsonb WHERE publisher_id = {pid} AND feed_url = '{url}' AND parser_config = '{{"undated": "fetch_time"}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: parser_config back to '{{}}' (one transaction), then the backfilled dates back to NULL in batches. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
{rev}END $do$;
COMMIT;
CREATE TEMP TABLE batch_ids AS
  SELECT id, ((row_number() OVER (ORDER BY id)) - 1) / 500 AS b FROM articles WHERE publisher_id IN ({IDS}) AND published_at = fetched_at;
SET statement_timeout = '15s';
SELECT format('UPDATE articles a SET published_at = NULL FROM batch_ids i WHERE i.b = %s AND a.id = i.id AND a.published_at = a.fetched_at', b), 'SELECT pg_sleep(4)'
  FROM generate_series(0, coalesce((SELECT max(b) FROM batch_ids), -1)) b ORDER BY b
\\gexec
RESET statement_timeout;
{COUNT}
""")
print('ok')
