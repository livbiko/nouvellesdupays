# Generates apply.sql, rehearse.sql (same body, ROLLBACK), reverse.sql and verify.sql for the six Egyptian sources.
# Mirrors POST /api/admin/submissions/:id/approve (feed branch): submission -> publisher (active) + feed + submission approved,
# with the same refusal as findPublisherConflict (same name or domain in the country, or same feed URL).
TAG = '[added by Claude on owner request 2026-10-15, Egypt sources]'
# name, homepage, feed, feed_type, language, domain, source_type, probe note
SRC = [
    ('Daily News Egypt', 'https://www.dailynewsegypt.com', 'https://www.dailynewsegypt.com/feed/', 'rss', 'en', 'dailynewsegypt.com', 'NEWSPAPER', 'rss, 10 items, newest 2026-10-15 14:10 UTC'),
    ('Egyptian Streets', 'https://egyptianstreets.com', 'https://egyptianstreets.com/feed/', 'rss', 'en', 'egyptianstreets.com', 'ONLINE_NEWS', 'rss, 9 items, newest 2026-10-15 10:50 UTC'),
    ('Mada Masr', 'https://www.madamasr.com', 'https://www.madamasr.com/feed/', 'rss', 'ar', 'madamasr.com', 'ONLINE_NEWS', 'rss, 10 items, newest 2026-10-15 17:39 UTC'),
    ('El Watan News', 'https://www.elwatannews.com', 'https://www.elwatannews.com/news-sitemap.xml', 'sitemap-news', 'ar', 'elwatannews.com', 'NEWSPAPER', 'sitemap-news, 1000 items, newest 2026-10-15 17:02 UTC'),
    ('Al Borsa', 'https://www.alborsaanews.com', 'https://www.alborsaanews.com/feed', 'rss', 'ar', 'alborsaanews.com', 'FINANCIAL', 'rss, 20 items, newest 2026-10-15 17:57 UTC'),
    ('Cairo 24', 'https://www.cairo24.com', 'https://www.cairo24.com/rss.aspx', 'rss', 'ar', 'cairo24.com', 'ONLINE_NEWS', 'rss, 30 items, newest 2026-10-15 21:10 UTC'),
]
N = len(SRC)


def q(s):
    return "'" + s.replace("'", "''") + "'"


ROWS = ',\n  '.join(f"({q(n)}, {q(h)}, {q(f)}, {q(t)}, {q(l)}, {q(d)}, {q(st)}, {q(note)})" for (n, h, f, t, l, d, st, note) in SRC)
TAGGED = f"verification_detail LIKE '%' || {q(TAG)}"
HDR = '\\set ON_ERROR_STOP on\n'

BODY = f"""SET lock_timeout = '5s';
BEGIN;
CREATE TEMP TABLE src (name text, homepage text, feed text, feed_type text, lang text, domain text, source_type text, note text) ON COMMIT DROP;
INSERT INTO src VALUES
  {ROWS};
DO $$
DECLARE eg int; bad int; s record; sid int; pid int; n int := 0;
BEGIN
  SELECT id INTO eg FROM countries WHERE iso_code = 'EG';
  IF eg IS NULL THEN RAISE EXCEPTION 'no EG country'; END IF;
  -- Same refusal as findPublisherConflict, plus an earlier run of this script.
  SELECT count(*) INTO bad FROM src x
   WHERE EXISTS (SELECT 1 FROM publishers p WHERE p.country_id = eg AND (lower(p.name) = lower(x.name)
                 OR lower(regexp_replace(regexp_replace(p.domain, '^www[.]', ''), '/+$', '')) = x.domain))
      OR EXISTS (SELECT 1 FROM feeds f WHERE f.feed_url = x.feed)
      OR EXISTS (SELECT 1 FROM publisher_submissions ps WHERE ps.{TAGGED});
  IF bad > 0 THEN RAISE EXCEPTION '% of {N} already exist as a publisher, feed or earlier run - nothing changed', bad; END IF;
  FOR s IN SELECT * FROM src ORDER BY name LOOP
    INSERT INTO publisher_submissions (name, homepage_url, feed_url, feed_type, country_id, language, feed_verified,
      verification_detail, domain, ingestion_method, status, status_changed_at, reviewed_at)
    VALUES (s.name, s.homepage, s.feed, s.feed_type, eg, s.lang, true,
      'Feed checked from the cluster 2026-10-15: ' || s.note || ' ' || {q(TAG)}, s.domain, 'feed', 'approved', now(), now())
    RETURNING id INTO sid;
    INSERT INTO publishers (country_id, name, homepage_url, feed_status, language, domain, source_type)
    VALUES (eg, s.name, s.homepage, 'active', s.lang, s.domain, s.source_type) RETURNING id INTO pid;
    INSERT INTO feeds (publisher_id, feed_url, feed_type) VALUES (pid, s.feed, s.feed_type);
    UPDATE publisher_submissions SET publisher_id = pid WHERE id = sid;
    n := n + 1;
  END LOOP;
  IF n <> {N} THEN RAISE EXCEPTION 'added %, expected {N}', n; END IF;
END $$;
SELECT 'added|' || s.id || '|' || s.status || '|' || p.id || '|' || p.name || '|' || p.feed_status || '|' || p.language || '|' || p.source_type
       || '|' || f.id || '|' || f.feed_type || '|' || f.feed_url
  FROM publisher_submissions s JOIN publishers p ON p.id = s.publisher_id JOIN feeds f ON f.publisher_id = p.id
 WHERE s.{TAGGED} ORDER BY p.id;
SELECT 'egypt|' || count(*) FILTER (WHERE p.feed_status = 'active') || ' active of ' || count(*)
  FROM publishers p JOIN countries c ON c.id = p.country_id WHERE c.iso_code = 'EG';"""

with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Six Egyptian sources (data only, MEDIUM). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')

with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n'
             f"SELECT 'rolledback|' || count(*) || ' tagged submissions left' FROM publisher_submissions WHERE {TAGGED};\n")

with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: removes the six publishers, their feeds, their articles and the submissions (found by the tag).
-- Meant for the release window (a few hours of articles); one transaction. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
CREATE TEMP TABLE gone ON COMMIT DROP AS
  SELECT s.id AS sub, s.publisher_id AS pub FROM publisher_submissions s WHERE s.{TAGGED};
DO $$ DECLARE n int; BEGIN SELECT count(*) INTO n FROM gone; IF n <> {N} THEN RAISE EXCEPTION 'found % tagged submissions, expected {N}', n; END IF; END $$;
SELECT 'articles|' || count(*) FROM articles WHERE publisher_id IN (SELECT pub FROM gone);
DELETE FROM articles WHERE publisher_id IN (SELECT pub FROM gone);
DELETE FROM feeds WHERE publisher_id IN (SELECT pub FROM gone);
DELETE FROM editorial_profiles WHERE publisher_id IN (SELECT pub FROM gone);
UPDATE publisher_submissions SET publisher_id = NULL WHERE id IN (SELECT sub FROM gone);
DELETE FROM publishers WHERE id IN (SELECT pub FROM gone);
DELETE FROM publisher_submissions WHERE id IN (SELECT sub FROM gone);
COMMIT;
SELECT 'reversed|' || count(*) || ' tagged submissions left' FROM publisher_submissions WHERE {TAGGED};
""")

with open('verify.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Read-only, after the first poll. Generated by Build-Sql.py.
SELECT 'feed|' || p.id || '|' || p.name || '|' || f.consecutive_failures || '|' || coalesce(to_char(f.last_success_at, 'HH24:MI'), 'never')
       || '|' || coalesce(left(f.last_error, 80), '-')
       || '|' || (SELECT count(*) FROM articles a WHERE a.publisher_id = p.id) || ' art'
       || '|' || (SELECT count(*) FROM articles a WHERE a.publisher_id = p.id AND a.published_at IS NULL) || ' undated'
       || '|' || coalesce((SELECT to_char(min(a.published_at), 'MM-DD HH24:MI') || '..' || to_char(max(a.published_at), 'MM-DD HH24:MI')
                           FROM articles a WHERE a.publisher_id = p.id), '-')
  FROM publisher_submissions s JOIN publishers p ON p.id = s.publisher_id JOIN feeds f ON f.publisher_id = p.id
 WHERE s.{TAGGED} ORDER BY p.id;
SELECT 'ok|' || count(*) FILTER (WHERE f.last_success_at > now() - interval '30 minutes') || ' of {N}'
  FROM publisher_submissions s JOIN feeds f ON f.publisher_id = s.publisher_id WHERE s.{TAGGED};
SELECT 'sample|' || p.name || '|' || a.category || '|' || left(a.headline, 80)
  FROM articles a JOIN publishers p ON p.id = a.publisher_id
 WHERE a.id IN (SELECT max(a2.id) FROM articles a2 JOIN publisher_submissions s ON s.publisher_id = a2.publisher_id
                WHERE s.{TAGGED} GROUP BY a2.publisher_id);
""")
print('ok', N)
