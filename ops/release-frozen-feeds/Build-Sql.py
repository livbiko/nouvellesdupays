# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql for the frozen-feed fix (2026-10-17).
# These 8 feeds answered 200 with 'ok' but their newest items were months or years old (El País 2020, ABC 2016, ...),
# so every item fell outside the worker's 14-day window and nothing was ever inserted. Each outlet's current feed was
# found on its homepage (<link rel=alternate>) or robots.txt, and tested with the worker's own parser + buildArticleRow.
# Every UPDATE is guarded on publisher, old URL, old type and enabled; the transaction aborts unless each matches 1 row.

FEEDS = [  # publisher_id, name, old_url, new_url, new_type, tested (usable items / items, newest)
    (531, 'El País (ES)', 'https://www.elpais.com/rss/elpais/portada.xml', 'https://feeds.elpais.com/mrss-s/pages/ep/site/elpais.com/portada', 'rss', '147/148, 2026-10-17'),
    (532, 'ABC', 'https://www.abc.es/rss/feeds/abcPortada.xml', 'https://www.abc.es/rss/2.0/portada/', 'rss', '25/25, 2026-10-17'),
    (536, 'Corriere della Sera', 'https://www.corriere.it/rss/homepage.xml', 'https://www.corriere.it/feed-hp/homepage-restyle-2025.xml', 'rss', '117/138, 2026-10-17'),
    (1011, 'The Business Standard', 'https://tbsnews.net/rss.xml', 'https://www.tbsnews.net/top-news/rss.xml', 'rss', '20/20, 2026-10-17'),
    (60, 'NHK', 'https://www3.nhk.or.jp/rss/news/cat0.xml', 'https://www.nhk.or.jp/rss/news/cat0.xml', 'rss', '7/7, 2026-10-17'),
    (5175, 'Agence Ecofin', 'https://www.agenceecofin.com/feed', 'https://www.agenceecofin.com/component/obrss/agence-ecofin-full', 'rss', '30/30, 2026-10-17'),
    (1007, 'The News International', 'https://www.thenews.com.pk/rss/1/1', 'https://www.thenews.com.pk/assets/uploads/google_news_latest.xml', 'sitemap-news', '100/100, 2026-10-17'),
    (1009, 'The Daily Star', 'https://www.thedailystar.net/rss.xml', 'https://www.thedailystar.net/googlenews.xml', 'sitemap-news', '270/270, 2026-10-17'),
]
IDS = ', '.join(str(f[0]) for f in FEEDS)

for f in FEEDS:
    assert "'" not in f[2] + f[3]

steps = ''
for pid, name, old, new, typ, _ in FEEDS:
    steps += f"""  UPDATE feeds SET feed_url = '{new}', feed_type = '{typ}', etag = NULL, last_modified = NULL
   WHERE publisher_id = {pid} AND feed_url = '{old}' AND feed_type = 'rss' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % feed rows at the old URL, expected 1 - nothing changed', k; END IF;
"""

BODY = f"""SET lock_timeout = '5s';
BEGIN;
SELECT 'before|' || publisher_id || '|' || feed_type || '|' || feed_url FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'after|' || publisher_id || '|' || feed_type || '|' || feed_url FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;"""

rev = ''
for pid, name, old, new, typ, _ in FEEDS:
    rev += f"""  UPDATE feeds SET feed_url = '{old}', feed_type = 'rss', etag = NULL, last_modified = NULL WHERE publisher_id = {pid} AND feed_url = '{new}' AND enabled;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Frozen feeds: 8 feed URLs replaced by the outlets\' current feeds (data only). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || publisher_id || '|' || feed_url FROM feeds WHERE publisher_id IN ({IDS}) AND enabled ORDER BY publisher_id;\n")
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Reverse of apply.sql (articles ingested from the new feeds stay). Generated by Build-Sql.py.\n{HDR}SET lock_timeout = '5s';\nBEGIN;\nDO $do$ DECLARE k int; BEGIN\n{rev}END $do$;\nCOMMIT;\n")
print('ok')
