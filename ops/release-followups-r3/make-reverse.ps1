# Writes reverse.sql from before.txt (snapshot.sql output): undoes apply.sql exactly.
# Removes the 4 new publishers (with whatever they collected) and NBC's new nbcnews.na source, then puts every changed row
# back to its snapshot values. Refuses if the new publishers were worked on (contacts, profiles, videos) or if any of
# the 6 submissions was handled after the release.
Set-Location $PSScriptRoot
$snap = Get-Content before.txt | Where-Object { $_ -match '^snap\|' }
if ($snap.Count -ne 14) { throw "before.txt has $($snap.Count) snapshot rows, expected 14" }
$cols = @{
  publishers            = 'homepage_url, domain, feed_status, source_type'
  feeds                 = 'enabled'
  publisher_submissions = 'status, publisher_id, reviewer_note, reviewed_at, status_changed_at'
  discovered_sources    = 'status, notes, updated_at, promoted_submission_id'
}
$restore = foreach ($line in $snap) {
  $f = $line -split '\|'
  $t = $f[1]; $b64 = $f[2]
  $set = ($cols[$t] -split ', ' | ForEach-Object { "$_ = r.$_" }) -join ', '
  "UPDATE $t t SET $set FROM json_populate_record(NULL::$t, convert_from(decode('$b64', 'base64'), 'UTF8')::json) r WHERE t.id = r.id;"
}
@"
-- Generated by make-reverse.ps1 from before.txt. Undoes apply.sql (round-3 follow-ups). One transaction.
\set ON_ERROR_STOP on
BEGIN;
CREATE TEMP TABLE newpub ON COMMIT DROP AS SELECT publisher_id AS id FROM publisher_submissions WHERE id IN (168, 169, 170, 171) AND publisher_id IS NOT NULL;
CREATE TEMP TABLE newfeed ON COMMIT DROP AS
  SELECT id FROM feeds WHERE publisher_id IN (SELECT id FROM newpub) OR (publisher_id = 270 AND feed_url = 'https://nbcnews.na/rss.xml');
DO `$`$
BEGIN
  IF (SELECT count(*) FROM newpub) <> 4 THEN RAISE EXCEPTION 'expected 4 new publishers from 168-171 - not reverting'; END IF;
  IF (SELECT count(*) FROM newfeed) <> 5 THEN RAISE EXCEPTION 'expected 5 new sources - not reverting'; END IF;
  IF EXISTS (SELECT 1 FROM publisher_submissions WHERE (id = 137 AND status <> 'rejected') OR (id = 161 AND status <> 'suspended')
             OR (id IN (168, 169, 170) AND status <> 'approved') OR (id = 171 AND status <> 'active')) THEN
    RAISE EXCEPTION 'a submission was handled after the release - not reverting'; END IF;
  IF EXISTS (SELECT 1 FROM contacts WHERE publisher_id IN (SELECT id FROM newpub))
     OR EXISTS (SELECT 1 FROM editorial_profiles WHERE publisher_id IN (SELECT id FROM newpub))
     OR EXISTS (SELECT 1 FROM youtube_videos WHERE publisher_id IN (SELECT id FROM newpub)) THEN
    RAISE EXCEPTION 'the new publishers have contacts, profiles or videos - not reverting'; END IF;
END `$`$;
UPDATE discovered_sources SET discovered_from_publisher_id = NULL WHERE discovered_from_publisher_id IN (SELECT id FROM newpub);
DELETE FROM discovery_mining_log WHERE publisher_id IN (SELECT id FROM newpub);
DELETE FROM source_scores WHERE publisher_id IN (SELECT id FROM newpub);
DELETE FROM articles WHERE feed_id IN (SELECT id FROM newfeed) OR publisher_id IN (SELECT id FROM newpub);
DELETE FROM feeds WHERE id IN (SELECT id FROM newfeed);
$($restore -join "`n")
DELETE FROM publishers WHERE id IN (SELECT id FROM newpub);
SELECT 'reverted|' || (SELECT count(*) FROM newpub) || ' publishers, ' || (SELECT count(*) FROM newfeed) || ' sources removed; 14 rows restored';
COMMIT;
"@ | Set-Content reverse.sql -Encoding ASCII
