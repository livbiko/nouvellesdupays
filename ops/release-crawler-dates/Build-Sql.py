# Generates apply.sql, rehearse.sql (same body, ROLLBACK) and reverse.sql: date rules for crawled sources whose every article
# was stored undated (2026-10-17 undated.sql). Needs the worker image with the crawler change (word dates in labelledDate,
# trimmed JSON-LD datePublished, branch feat/crawler-word-dates) -- Run-Release.ps1 deploys it first.
#  - Seychelles Nation: "<span class="date">|17 October 2026" (UTC+4)
#  - ENA: og:description starts "Addis Ababa, October 17, 2026 (ENA)" (UTC+3)
#  - Courrier Confidentiel: og:image file name ".../actualites/Courrier-Confidentiel-14-10-2026-14-23-31-..." (numeric, works today)
#  - TNX Africa: no config; its JSON-LD date only needed the trim.
# Dry run of all four with the new code: 6/6 dated each. last_fetched_at is cleared so they are crawled on the next run
# (they run hourly) instead of up to an hour later. GRTS and Inforpress are left out: no date tied to the article.
import json

FEEDS = [  # publisher_id, feed_id, name, parser_config (None = only re-crawl)
    (8949, 8947, 'Seychelles Nation', {'date_after_label': 'class="date"', 'utc_offset': '+04:00'}),
    (8950, 8948, 'ENA (Ethiopian News Agency)', {'date_after_label': 'property="og:description"', 'utc_offset': '+03:00'}),
    (8956, 8954, 'Courrier Confidentiel', {'date_after_label': 'actualites/Courrier-Confidentiel-', 'date_format': 'DD-MM-YYYY'}),
    (8965, 8965, 'TNX Africa', None),
]
IDS = ', '.join(str(f[1]) for f in FEEDS)


def lit(cfg):
    s = json.dumps(cfg)
    assert "'" not in s
    return f"'{s}'::jsonb"


steps = ''
for pid, fid, name, cfg in FEEDS:
    sets = (f'parser_config = {lit(cfg)}, ' if cfg else '') + 'last_fetched_at = NULL'
    steps += f"""  UPDATE feeds SET {sets}
   WHERE id = {fid} AND publisher_id = {pid} AND feed_type = 'html' AND enabled AND parser_config = '{{}}'::jsonb;
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{name}: feed {fid} not the enabled html source with an empty parser_config - nothing changed'; END IF;
"""

BODY = f"""SET lock_timeout = '5s';
BEGIN;
DO $do$
DECLARE k int;
BEGIN
{steps}END $do$;
SELECT 'after|' || publisher_id || '|' || id || '|' || parser_config::text || '|' || coalesce(last_fetched_at::text, 'due') FROM feeds WHERE id IN ({IDS}) ORDER BY publisher_id;"""

rev = ''
for pid, fid, name, cfg in FEEDS:
    if cfg:
        rev += f"""  UPDATE feeds SET parser_config = '{{}}'::jsonb WHERE id = {fid} AND parser_config = {lit(cfg)};
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{fid}: % rows, expected 1', k; END IF;
"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Crawled-source date rules (data only; run after the worker image with word dates). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             f"SELECT 'rolledback|' || publisher_id || '|' || parser_config::text FROM feeds WHERE id IN ({IDS}) ORDER BY publisher_id;\n")
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Reverse of apply.sql: parser_config back to '{{}}' (the crawl-time reset needs no undoing). Generated by Build-Sql.py.\n"
             f"{HDR}SET lock_timeout = '5s';\nBEGIN;\nDO $do$ DECLARE k int; BEGIN\n{rev}END $do$;\nCOMMIT;\n")
print('ok')
