# Generates apply.sql, rehearse.sql (same body, ROLLBACK), reverse.sql and expect.txt:
#  - Journal de Kinshasa (5299) and Journal du Tchad (216): replace their 2026-09-14 unknown/low profiles with Yogam Group ones.
#  - Journal du Tchad: homepage_url https://www.journaldutchad.com -> https://journaldutchad.com (www. serves a certificate for another name).
# Every UPDATE is guarded on the full current value (the old texts below were read from the public API on 2026-10-16),
# so reverse.sql restores them exactly; the transaction aborts unless each statement touches exactly one row.
import json

D = '2026-10-16'
OLD_DATE = '2026-09-14'
OLD = {  # publisher_id: (name, iso, current_context, evidence_summary)
    5299: ('Journal de Kinshasa', 'CD', 'Aucune information de propriété accessible lors de cette recherche.',
           'Recherche infructueuse -- classification "non évalué".'),
    216: ('Journal du Tchad', 'TD', 'ALERTE : domaine journaldutchad.com ne résout plus (échec DNS confirmé) lors de cette vérification.',
          'Domaine possiblement mort -- à vérifier opérationnellement.'),
}
OLD_HOME_216 = 'https://www.journaldutchad.com'
NEW_HOME_216 = 'https://journaldutchad.com'


def src(url, note, category):
    return {'url': url, 'note': note, 'category': category, 'accessed_at': D}


exec(open('profiles.py', encoding='utf-8').read())
assert sorted(p[0] for p in P) == sorted(OLD)


def dq(s):
    if s is None:
        return 'NULL'
    assert '$$' not in s
    return f'$${s}$$'


def update(p):
    (pid, name, iso, otype, owner, tags, party, hist, cur, conf, summ, sources, review) = p
    oname, oiso, ocur, osumm = OLD[pid]
    assert (name, iso) == (oname, oiso)
    tags_sql = 'ARRAY[' + ', '.join(f"'{t}'" for t in tags) + ']::text[]'
    return f"""  PERFORM 1 FROM publishers p JOIN countries c ON c.id = p.country_id WHERE p.id = {pid} AND p.name = {dq(name)} AND c.iso_code = '{iso}' AND p.feed_status = 'active';
  IF NOT FOUND THEN RAISE EXCEPTION '{pid}: publisher not as expected - nothing changed'; END IF;
  UPDATE editorial_profiles SET ownership_type = {dq(otype)}, owner = {dq(owner)}, classification_tags = {tags_sql},
    political_party_association = {dq(party)}, historical_context = {dq(hist)}, current_context = {dq(cur)}, confidence = '{conf}',
    evidence_summary = {dq(summ)}, evidence_sources = {dq(json.dumps(sources, ensure_ascii=False))}::jsonb,
    classification_date = DATE '{D}', last_reviewed = DATE '{D}', evidence_date = DATE '{D}', review_required = {'true' if review else 'false'}, updated_at = now()
   WHERE publisher_id = {pid} AND classification_date = DATE '{OLD_DATE}' AND classification_tags = ARRAY['unknown']::text[] AND confidence = 'low'
     AND owner IS NULL AND ownership_type IS NULL AND current_context = {dq(ocur)} AND evidence_summary = {dq(osumm)};
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: profile not at its 2026-09-14 values (% rows) - nothing changed', k; END IF;
"""


BODY = f"""SET lock_timeout = '5s';
BEGIN;
SELECT 'before|' || e.publisher_id || '|' || array_to_string(e.classification_tags, ',') || '|' || e.confidence || '|' || e.classification_date FROM editorial_profiles e WHERE e.publisher_id IN (5299, 216) ORDER BY e.publisher_id;
SELECT 'before|home|' || homepage_url FROM publishers WHERE id = 216;
DO $do$
DECLARE k int;
BEGIN
{''.join(update(p) for p in P)}  UPDATE publishers SET homepage_url = '{NEW_HOME_216}' WHERE id = 216 AND homepage_url = '{OLD_HOME_216}' AND domain = 'journaldutchad.com';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'Journal du Tchad homepage: % rows, expected 1 - nothing changed', k; END IF;
END $do$;
SELECT 'profile|' || e.publisher_id || '|' || array_to_string(e.classification_tags, ',') || '|' || e.confidence || '|' || e.classification_date || '|' || left(e.owner, 40) FROM editorial_profiles e WHERE e.publisher_id IN (5299, 216) ORDER BY e.publisher_id;
SELECT 'after|home|' || homepage_url FROM publishers WHERE id = 216;"""

HDR = '\\set ON_ERROR_STOP on\n'
with open('apply.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f'-- Journal de Kinshasa + Journal du Tchad: Yogam Group profiles; Tchad homepage www -> apex (data only). Generated by Build-Sql.py. Reverse: reverse.sql.\n{HDR}{BODY}\nCOMMIT;\n')
with open('rehearse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"-- Rehearsal of apply.sql: same statements, then ROLLBACK. Generated by Build-Sql.py.\n{HDR}{BODY}\nROLLBACK;\n"
             "SELECT 'rolledback|' || e.publisher_id || '|' || array_to_string(e.classification_tags, ',') || '|' || e.classification_date FROM editorial_profiles e WHERE e.publisher_id IN (5299, 216) ORDER BY e.publisher_id;\n")

rev = ''
for pid, (name, iso, ocur, osumm) in OLD.items():
    rev += f"""  UPDATE editorial_profiles SET ownership_type = NULL, owner = NULL, classification_tags = ARRAY['unknown']::text[], political_party_association = NULL,
    historical_context = NULL, current_context = {dq(ocur)}, confidence = 'low', evidence_summary = {dq(osumm)}, evidence_sources = '[]'::jsonb,
    classification_date = DATE '{OLD_DATE}', last_reviewed = DATE '{OLD_DATE}', evidence_date = DATE '{OLD_DATE}', review_required = true, updated_at = now()
   WHERE publisher_id = {pid} AND classification_date = DATE '{D}' AND owner LIKE 'Yogam Group SAS%';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION '{pid}: % rows, expected 1', k; END IF;
"""
with open('reverse.sql', 'w', newline='\n', encoding='utf-8') as fh:
    fh.write(f"""-- Reverse of apply.sql: restores the 2026-09-14 profiles and the old Journal du Tchad homepage. Generated by Build-Sql.py.
{HDR}SET lock_timeout = '5s';
BEGIN;
DO $do$ DECLARE k int; BEGIN
{rev}  UPDATE publishers SET homepage_url = '{OLD_HOME_216}' WHERE id = 216 AND homepage_url = '{NEW_HOME_216}';
  GET DIAGNOSTICS k = ROW_COUNT; IF k <> 1 THEN RAISE EXCEPTION 'homepage: % rows, expected 1', k; END IF;
END $do$;
COMMIT;
""")
with open('expect.txt', 'w', newline='\n', encoding='utf-8') as fh:
    for p in P:
        fh.write(f"{p[0]} {','.join(p[5])} {p[9]}\n")
